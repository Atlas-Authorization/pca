#!/usr/bin/env bash
# sync-goal-runner-copies.sh [--check]
# One source of truth for the goal semantics in every SDK test suite: packages/pca-conformance/runners/goal/<lang> is the runner;
# the SDKs' own goal tests (Ruby, .NET, Swift, Kotlin) run a GENERATED copy of it (headers say so) through a thin test glue.
# Without --check the copies are rewritten; with --check any drift fails.
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
R="$ROOT/packages/pca-conformance/runners/goal"
MODE="${1:-write}"
# the public flagship layout carries no sdks/ (the native repos hold their own copies): nothing to compare there
[ -d "$ROOT/sdks" ] || { echo "no sdks/ in this layout: nothing to check"; exit 0; }
fail=0
emit() { # <dest> <content-file>
  if [ "$MODE" = "--check" ]; then cmp -s "$2" "$1" || { echo "DRIFT: $1 differs from its runner source (run scripts/sync-goal-runner-copies.sh)"; fail=1; }
  else mkdir -p "$(dirname "$1")"; cp "$2" "$1"; fi
}
T="$(mktemp -d)"; trap 'rm -rf "$T"' EXIT
HDR="GENERATED by scripts/sync-goal-runner-copies.sh from packages/pca-conformance/runners/goal; do not edit."

# Ruby
{ echo "# $HDR"; cat "$R/ruby/run.rb"; } > "$T/rb"; emit "$ROOT/sdks/ruby-pca/test/goal_runner.rb" "$T/rb"
# .NET: the entry point is compiled out
{ echo "#define GOAL_AS_LIBRARY"; echo "// $HDR"; cat "$R/dotnet/run.cs"; } > "$T/cs"; emit "$ROOT/sdks/dotnet-pca/AtlasPca.Corpus.Tests/GoalRunner.cs" "$T/cs"
# Swift: every top-level declaration but the entry point is file-private (the test module has its own canon / S / O ...)
{ echo "// $HDR"; python3 - "$R/swift/GoalReplay.swift" <<'PY'
import re, sys
for line in open(sys.argv[1], encoding='utf-8').read().split('\n'):
    if re.match(r'(indirect enum|enum|struct|func|let|var|final class|class) ', line) and not line.startswith('func goalReplay'):
        line = 'fileprivate ' + line
    print(line)
PY
} > "$T/sw"; emit "$ROOT/sdks/swift-pca/Tests/AtlasPCAVerifyTests/GoalReplay.swift" "$T/sw"
# Kotlin: its own package (the test package has unrelated top-level names)
{ echo "// $HDR"; echo "package net.atlasauth.pca.verifier.goalrunner"; echo; cat "$R/kotlin/Run.kt"; } > "$T/kt"
emit "$ROOT/sdks/kotlin-pca/src/test/kotlin/net/atlasauth/pca/verifier/goalrunner/GoalRunner.kt" "$T/kt"
# Java: its own package; the class stays public (the test calls Run.replay)
{ echo "// $HDR"; echo "package net.atlasauth.pca.goalrunner;"; echo; cat "$R/java/Run.java"; } > "$T/jv"
emit "$ROOT/sdks/java-pca/test/net/atlasauth/pca/goalrunner/Run.java" "$T/jv"
[ "$fail" = 0 ] && echo "goal runner copies: OK" || exit 1
