#!/usr/bin/env python3
"""Mutation layout only: ONE test target for all of a crate's integration tests.

  aggregate-tests.py CRATE_DIR            write tests/all_mutation.rs and switch Cargo.toml to it (autotests = false + [[test]] all)
  aggregate-tests.py CRATE_DIR --check    verify an existing layout (no write): every tests/*.rs included exactly once, no stray [[test]]

Every mutant relinks every test binary; 290 files = 290 binaries. Here each tests/X.rs becomes `#[path = "X.rs"] mod X;` of a single
crate (nextest still runs one process per test). Why this is sound:
  - a #[path] module file is a mod-rs file: its `mod common;` / `#[path = "producer/ops.rs"] mod ops;` / include_str! resolve against
    tests/ exactly as before; each file gets its own copy of `common` (distinct modules, so nothing is shared by accident);
  - inner attributes (#![cfg(feature = "axum")], #![cfg(unix)], #![allow(..)]) stay at the top of the module file and apply to the module;
  - tests that re-run the binary with --exact use test_name() (tests/baseb_re1.rs, baseb_re2.rs, durable_state.rs, ref_state_guard.rs):
    the libtest name gains the `<file>::` prefix;
  - there are no [[test]] entries (so no per-target required-features), which the check enforces."""
import glob, os, re, sys

crate = sys.argv[1]
check = "--check" in sys.argv
tests = os.path.join(crate, "tests")
AGG = "all_mutation.rs"
files = sorted(os.path.basename(f) for f in glob.glob(os.path.join(tests, "*.rs")) if os.path.basename(f) != AGG)
if not files:
    sys.exit(f"{tests}: no test files")
bad = [f for f in files if not re.fullmatch(r"[a-z][a-z0-9_]*\.rs", f)]
if bad:
    sys.exit(f"test file names that are not module names: {bad}")
body = "// GENERATED by tools/pca-audit/rust-mutate/aggregate-tests.py (mutation layout only; never committed).\n" + "".join(
    f'#[path = "{f}"]\nmod {f[:-3]};\n' for f in files)
toml_p = os.path.join(crate, "Cargo.toml")
toml = open(toml_p, encoding="utf-8").read()
AGG_TOML = '\n[[test]]\nname = "all"\npath = "tests/all_mutation.rs"\n'

# the [[test]] tables the manifest already has: none may exist besides ours (a per-target required-features would be lost)
manifest_tests = re.findall(r"^\[\[test\]\]\s*\n(?:[^\[]*?)name\s*=\s*\"([^\"]+)\"", toml, re.M)
others = [t for t in manifest_tests if t != "all"]
if others:
    sys.exit(f"Cargo.toml declares [[test]] {others}: convert each one's required-features to #[cfg(feature)] on its module first")

if check:
    got = open(os.path.join(tests, AGG), encoding="utf-8").read()
    mods = re.findall(r'^#\[path = "([^"]+)"\]\nmod (\w+);$', got, re.M)
    inc = [p for p, _ in mods]
    dup = sorted({p for p in inc if inc.count(p) > 1})
    if dup or sorted(inc) != files or any(p[:-3] != m for p, m in mods):
        sys.exit(f"aggregate target out of step: duplicates {dup}, missing {sorted(set(files) - set(inc))}, unknown {sorted(set(inc) - set(files))}")
    if "autotests = false" not in toml or manifest_tests.count("all") != 1:
        sys.exit("Cargo.toml is not switched to the aggregate target")
    print(f"aggregate target: {len(files)} test files, each included once")
    sys.exit(0)

# inside the aggregate `crate` is all_mutation.rs, not the test file: a test module must reach its root through super::
for f in sorted(glob.glob(os.path.join(tests, "**", "*.rs"), recursive=True)):
    if os.path.basename(f) != AGG and re.search(r"(?<![$\w])crate::", open(f, encoding="utf-8").read()):
        sys.exit(f"{f} uses crate::, which names the aggregate target here: use super:: (valid in both layouts)")

# a test that re-runs its own binary must name itself through test_name()
for f in files:
    s = open(os.path.join(tests, f), encoding="utf-8").read()
    if "current_exe" in s and "test_name(" not in s:
        sys.exit(f"tests/{f} re-runs current_exe() without test_name(): its --exact filter would not match inside the aggregate target")

open(os.path.join(tests, AGG), "w", encoding="utf-8").write(body)
if "autotests" not in toml:
    toml = toml.replace('build = "build.rs"\n', 'build = "build.rs"\nautotests = false\n', 1)
    assert "autotests = false" in toml, "no `build = \"build.rs\"` line to hang autotests on"
if "[[test]]" not in toml:
    toml += AGG_TOML
open(toml_p, "w", encoding="utf-8").write(toml)
print(f"wrote {tests}/{AGG}: {len(files)} modules")
