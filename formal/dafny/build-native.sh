#!/usr/bin/env bash
# build-native.sh [--check] [targets...]   targets: java cs go py (default: all four)
#   Compiles the proved goal kernel (Goal.dfy: GoalApi and the modules it includes, the same sources build-ext.sh compiles to
#   packages/pca-verified-core/generated/pca_goal.js) with the pinned Dafny (TOOLCHAIN.lock) to Java, C#, Go and Python, and
#   writes each extraction into its native SDK:
#     java  sdks/java-pca/src/dafny-goal/                     (compiled with the SDK sources; loaded by net.atlasauth.pca.goal.GoalKernel)
#     cs    sdks/dotnet-pca/AtlasPca/GoalKernel/Generated/    (compiled into AtlasPca; loaded by AtlasPca.GoalPkg.GoalKernel)
#     go    sdks/go-pca/goalkernel/internal/gen/              (imported by package goalkernel, build tag pcagoalkernel)
#     py    sdks/python-pca/atlas_pca/goal_kernel_gen/        (loaded by atlas_pca.goal_kernel; imports namespaced by py-namespace.py)
#   (default)  write the extractions (README.md in each directory is kept, every other file is replaced)
#   --check    build into a temp dir and fail unless every committed extraction is byte-identical to the fresh one
# Needs `dafny` (the pinned version: run verify-toolchain.sh --install first) and, for go, `gofmt` + goimports (installed pinned below).
# Translation only (--no-verify): the proofs of these exact sources run in the verified-core workflow (`build-ext.sh Goal --check`).
set -euo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"
ROOT="$(cd "$HERE/../.." && pwd)"
MODE=build
TARGETS=""
for a in "$@"; do case "$a" in --check) MODE=check;; java|cs|go|py) TARGETS="$TARGETS $a";; *) echo "unknown arg $a" >&2; exit 2;; esac; done
TARGETS="${TARGETS:- java cs go py}"
GO_MODULE=github.com/Atlas-Authorization/pca-go
GOIMPORTS_VERSION=v0.24.0   # Dafny's Go backend shells out to goimports (same pin as difftargets/build-targets.sh)

command -v dafny >/dev/null || { echo "dafny not on PATH (formal/dafny/verify-toolchain.sh --install --dir DIR, then add DIR to PATH)" >&2; exit 2; }
. "$HERE/TOOLCHAIN.lock"
v="$(dafny --version | tr -d '\r' | head -1)"
[ "$v" = "$DAFNY_VERSION_STRING" ] || { echo "dafny is '$v', TOOLCHAIN.lock pins '$DAFNY_VERSION_STRING'" >&2; exit 1; }
# the trusted-base rule of build-ext.sh, over every file Goal.dfy includes
for f in Goal.dfy GoalIr.dfy GoalCompile.dfy GoalWitness.dfy GoalRender.dfy; do
  if grep -nE '^[^/]*(\bassume\b|\{:axiom\}|\{:extern|\bextern\b|\{:verify +false)' "$HERE/$f"; then echo "FORBIDDEN: assume/axiom/extern/verify-false in $f" >&2; exit 1; fi
done
if echo "$TARGETS" | grep -qw go; then
  export PATH="$(go env GOPATH)/bin:$PATH"
  command -v goimports >/dev/null || go install "golang.org/x/tools/cmd/goimports@$GOIMPORTS_VERSION"
fi

TMP="$(mktemp -d)"; trap 'rm -rf "$TMP"' EXIT
STAGE="$TMP/stage"
dest() { case "$1" in
  java) echo sdks/java-pca/src/dafny-goal;; cs) echo sdks/dotnet-pca/AtlasPca/GoalKernel/Generated;;
  go) echo sdks/go-pca/goalkernel/internal/gen;; py) echo sdks/python-pca/atlas_pca/goal_kernel_gen;; esac; }
# the directory of the translation that holds the GoalApi module (layouts differ per backend and Dafny release)
apidir() { local hit; hit="$(find "$1" \( -name GoalApi -o -name GoalApi.py \) | LC_ALL=C sort | head -1)"; [ -n "$hit" ] || { echo "no GoalApi in $1" >&2; exit 1; }; dirname "$hit"; }

for t in $TARGETS; do
  out="$TMP/$t"; d="$STAGE/$(dest "$t")"; mkdir -p "$out" "$d"
  echo "== dafny translate $t Goal.dfy"
  ( cd "$HERE" && dafny translate "$t" Goal.dfy --include-runtime --no-verify --allow-warnings -o "$out/pca_goal" )
  case "$t" in
    java)
      src="$(apidir "$out")"
      ( cd "$src" && find . -name '*.java' | LC_ALL=C sort | while read -r f; do mkdir -p "$d/$(dirname "$f")"; cp "$f" "$d/$f"; done )
      [ -d "$d/dafny" ] || { echo "the Java translation has no dafny/ runtime sources (--include-runtime); add org.dafny:DafnyRuntime:$DAFNY_VERSION to the SDK instead" >&2; exit 1; } ;;
    cs)
      n=0
      for f in $(find "$out" -name '*.cs' | LC_ALL=C sort); do   # the program and, with --include-runtime, the runtime
        # generated code: no nullable annotations, no analyzer noise in the SDK build
        { printf '// <auto-generated> Dafny %s translation of formal/dafny/Goal.dfy (formal/dafny/build-native.sh). Do not edit.\n#nullable disable\n#pragma warning disable\n' "$DAFNY_VERSION"; cat "$f"; } > "$d/$(basename "$f")"
        n=$((n+1))
      done
      [ "$n" -gt 0 ] || { echo "no C# output" >&2; exit 1; } ;;
    go)
      src="$(apidir "$out")"
      pkgs="$(cd "$src" && find . -mindepth 1 -maxdepth 1 -type d | sed 's|^\./||' | LC_ALL=C sort)"
      for p in $pkgs; do cp -R "$src/$p" "$d/$p"; done   # top-level .go files (the program's main package) are dropped
      find "$d" \( -name go.mod -o -name go.sum \) -delete   # one module: the SDK's
      # GOPATH-style imports ("GoalIr", "dafny", ...) -> this module's import path
      alt="$(echo $pkgs | tr ' ' '|')"
      find "$d" -name '*.go' -print0 | xargs -0 perl -pi -e 's{^(\s*(?:import\s+)?(?:[A-Za-z_][A-Za-z0-9_]*\s+)?)"('"$alt"')"(\s*)$}{$1"'"$GO_MODULE/goalkernel/internal/gen"'/$2"$3}'
      gofmt -w "$d"
      if grep -rnE '^\s*(import\s+)?([A-Za-z_][A-Za-z0-9_]*\s+)?"('"$alt"')"\s*$' "$d"; then echo "unrewritten Go import" >&2; exit 1; fi ;;
    py)
      src="$(apidir "$out")"
      cp -R "$src/." "$d/"
      find "$d" -name __pycache__ -prune -exec rm -rf {} +
      # the modules import each other by top-level name (GoalApi, GoalIr, _dafny, ...): namespace them under atlas_pca.goal_kernel_gen
      # so a second Dafny extraction in the same process cannot clash, and make the directory a package
      : > "$d/__init__.py"
      python3 "$HERE/py-namespace.py" "$d" atlas_pca.goal_kernel_gen ;;
  esac
  # the README of each extraction directory is committed by hand and never generated
  find "$d" -name README.md -delete
  echo "   $(find "$d" -type f | wc -l | tr -d ' ') files -> $(dest "$t")"
done

rc=0
for t in $TARGETS; do
  rel="$(dest "$t")"; mine="$ROOT/$rel"; fresh="$STAGE/$rel"
  if [ "$MODE" = check ]; then
    if [ -d "$mine" ] && diff -r -q -x README.md "$fresh" "$mine" >/dev/null; then echo "ok    $t: $rel == fresh translation"
    else echo "DRIFT $t: $rel differs from a fresh translation (run formal/dafny/build-native.sh $t and commit)"; diff -r -q -x README.md "$fresh" "$mine" 2>&1 | head -20 || true; rc=1; fi
  else
    mkdir -p "$mine"
    find "$mine" -mindepth 1 -maxdepth 1 ! -name README.md -exec rm -rf {} +
    cp -R "$fresh/." "$mine/"
    echo "wrote $rel"
  fi
done
exit $rc
