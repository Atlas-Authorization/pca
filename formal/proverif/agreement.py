#!/usr/bin/env python3
"""Builds AGREEMENT.md: every ProVerif result next to the corresponding Tamarin result (formal/tamarin/results)."""
import re, os, glob
here = os.path.dirname(os.path.abspath(__file__))
TAM = os.path.join(here, '..', 'tamarin', 'results')
PV = os.path.join(here, 'results')

def tam(fname):
    d = {}
    p = os.path.join(TAM, fname)
    if os.path.exists(p):
        for l in open(p):
            m = re.match(r'\s*(\w+) \(([\w-]+)\): (.*)', l)
            if m: d[m.group(1)] = (m.group(2), m.group(3).strip())
    return d

def pv(fname):
    d = {}
    p = os.path.join(PV, fname)
    if os.path.exists(p):
        for l in open(p):
            q, t, r = l.rstrip('\n').split(' | ', 2)
            v = re.search(r'(is true|is false|cannot be proved)\.?\)?$', r)
            d[q] = (v.group(1) if v else r[:60], t)
    return d

# (model-file stem, tamarin file stem, variant) ; lemma -> pv query
ACTN = {'authorization': 'authorization', 'leaf_signature_authenticity': 'leaf_signature_authenticity',
        'attenuation_root': 'attenuation_root', 'attenuation_hop': 'attenuation_hop', 'audience_binding': 'audience_binding',
        'replay_freedom_nonce': 'replay_freedom_nonce', 'replay_freedom_counter': 'replay_freedom_counter'}
THR = {k: k for k in ['stepup3_requires_principal', 'stepup3_requires_guardian', 'stepup2_compromised_agent_insufficient', 'stepup2_one_compromised_key_insufficient']}
EXE = {('pca_actn', 'executable_root_grant'): 'sanity1', ('pca_actn', 'executable_delegation_issued'): 'sanity4', ('pca_actn', 'executable_delegated'): 'sanity2',
       ('pca_threshold', 'executable_t3'): 'sanity3', ('pca_threshold', 'executable_t2'): 'sanity2', ('pca_attest', 'executable_attestation'): 'sanity2'}

rows = []
def add(model, variant, lemma, tkind, tres, pvq, pvres):
    ok = None
    if tres is not None and pvres is not None:
        if tkind == 'exists-trace': ok = (tres.startswith('verified') and pvres[0] == 'is false')
        else: ok = ((tres.startswith('verified') and pvres[0] == 'is true') or (tres.startswith('falsified') and pvres[0] == 'is false'))
    rows.append((model, variant or '(shipped)', lemma, tres or 'not run', pvq, pvres[0] if pvres else 'not run', pvres[1] if pvres else '', 'YES' if ok else ('NO' if ok is False else 'n/a')))

def models(model, tfile, pfile, variants, mapping, qmap_override=None):
    for var in variants:
        t = tam(f'{tfile}{"__"+var if var else ""}.txt')
        p = pv(f'{pfile}{"__"+var if var else ""}.txt')
        for lemma, (kind, res) in t.items():
            if lemma.startswith('executable'):
                continue
            q = (qmap_override or mapping).get(lemma)
            if q is None: continue
            add(model, var, lemma, kind, res, q, p.get(q))

models('pca_actn', 'pca_actn', 'pca_actn', ['', 'NO_GREF_CHECK', 'NO_ANCESTOR_CAV', 'NO_AUD_CHECK', 'NO_LEAF_SIG'], ACTN)
# expiry lemma lives in a separate ProVerif file
for var in ['', 'NO_EXPIRY_CHECK']:
    t = tam(f'pca_actn{"__"+var if var else ""}.txt').get('no_accept_after_expiry')
    p = pv(f'pca_actn_expiry{"__"+var if var else ""}.txt').get('no_accept_after_expiry')
    if t: add('pca_actn(+_expiry)', var, 'no_accept_after_expiry', t[0], t[1], 'no_accept_after_expiry', p)
models('pca_threshold', 'pca_threshold', 'pca_threshold', ['', 'UNBOUND_SHARE', 'NO_DISTINCT', 'NO_SET_DISTINCT'], THR)
models('pca_attest', 'pca_attest', 'pca_attest', ['', 'NOBIND_HOLDER', 'NOBIND_GRANT', 'NOBIND_EPOCH', 'NOBIND_NONCE'], {'attestation_binding': 'attestation_binding'})
for (m, lemma), q in EXE.items():
    t = tam(f'{m}.txt').get(lemma)
    p = pv(f'{m}__SANITY.txt').get(q)
    add(m, 'sanity (no Reveal)', lemma, t[0], t[1], q, p)

out = ['# ProVerif vs Tamarin agreement matrix', '',
       'Generated by `agreement.py` from `results/*.txt` (ProVerif 2.05) and `../tamarin/results/*.txt` (Tamarin 1.12.0). No prose beyond this table.',
       '', 'Mapping: Tamarin `verified` <-> ProVerif `is true`; Tamarin `falsified - found trace` <-> ProVerif `is false`; Tamarin exists-trace `verified` <-> ProVerif reachability query `is false` (event reachable).', '',
       '| Model | Variant | Tamarin lemma | Tamarin result | ProVerif query | ProVerif result | PV time | Agree |', '|---|---|---|---|---|---|---|---|']
for r in rows: out.append('| ' + ' | '.join(r) + ' |')
n = len(rows); ag = sum(1 for r in rows if r[-1] == 'YES')
out += ['', f'Compared pairs: {n}; agreeing: {ag}; disagreeing: {sum(1 for r in rows if r[-1]=="NO")}.', '']
# ProVerif-only queries
out += ['## ProVerif queries with no Tamarin counterpart', '', '| Model | Variant | Query | ProVerif result |', '|---|---|---|---|']
for f in sorted(glob.glob(os.path.join(PV, 'pca_*.txt'))):
    name = os.path.basename(f)[:-4]
    model, _, var = name.partition('__')
    for q, (res, t) in pv(os.path.basename(f)).items():
        if q.startswith('sanity'): continue
        tam_known = set(ACTN) | set(THR) | {'attestation_binding', 'no_accept_after_expiry'}
        if q in tam_known and not (model == 'pca_actn' and var in ('TABLE_CHECK_INSERT','TABLE_INSERT_FIRST')): continue
        out.append(f'| {model} | {var or "(shipped)"} | {q} | {res} |')
out += ['', '## ProVerif extra mutation checks (all queries, variants Tamarin did not run for that lemma)', '',
        '| Variant | Query | ProVerif result |', '|---|---|---|']
tam_pairs = {(r[1], r[4]) for r in rows}
for f in sorted(glob.glob(os.path.join(PV, 'pca_actn__*.txt')) + glob.glob(os.path.join(PV, 'pca_threshold__*.txt')) + glob.glob(os.path.join(PV, 'pca_attest__*.txt'))):
    name = os.path.basename(f)[:-4]; model, _, var = name.partition('__')
    if var in ('SANITY','TABLE_CHECK_INSERT','TABLE_INSERT_FIRST'): continue
    for q, (res, t) in pv(os.path.basename(f)).items():
        if (var, q) in tam_pairs: continue
        out.append(f'| {model}__{var} | {q} | {res} |')
open(os.path.join(here, 'AGREEMENT.md'), 'w').write('\n'.join(out) + '\n')
print(n, ag)
