/**
 * The plan types and the adapter from `pca init`'s plan. The plan is produced by `makePlan` of @atlasauth/pca-init (the same
 * function `npx @atlasauth/pca-cli init` runs), so the CLI and a coding agent can never be given different answers. This
 * module only reshapes it into structured steps. Nothing here touches the disk. Steps that need a human decision or signature
 * are marked `human: true`; a coding agent must stop and ask.
 */
import { createHash } from 'node:crypto';
import { InitError, makePlan, realDeps, type InitDeps, type Plan as InitPlan } from '@atlasauth/pca-init';
import type { Detection, Integration, Language } from './detect';

export interface PlanStep {
  id: string;
  kind: 'command' | 'create' | 'edit' | 'decision';
  title: string;
  /** Why this step exists. */
  why: string;
  command?: string;
  path?: string;
  /** For create: the whole file. For edit: the whole file as it should be afterwards. */
  content?: string;
  /** For an edit: sha256 of the file as the plan saw it (an edit is only applicable to exactly that file). */
  beforeDigest?: string;
  /** The `apply` step writes this too (key material is only ever generated there, never printed). */
  appliedBy?: string;
  /** Needs a human's decision or signature; the coding agent must not do it alone. */
  human?: boolean;
}
export interface Plan {
  integration: Integration;
  language: Language | null;
  mode: 'observe' | 'enforce';
  steps: PlanStep[];
  notes: string[];
  /** Reasons the plan cannot be applied at all (not even with a force). */
  blockers: string[];
  /** The git working tree has uncommitted changes: commit first so the changes can be reviewed and undone. */
  dirty: boolean;
  /** Commands that prove the integration works. */
  verify: string[];
  /** Rules for the coding agent applying the plan. */
  rules: string[];
  docs: string[];
}
export interface PlanOptions { integration?: Integration; namespace?: string; mode?: 'observe' | 'enforce' }
export type Planner = (root: string, d: Detection, o: PlanOptions) => Promise<Plan>;

export const RULES: string[] = [
  'Default deny: anything not mapped to an action is refused. Never add a catch-all allow.',
  'Observe first: run in observe mode, read the audit log, then enforce. Do not start in enforce on a service that is live.',
  'Never disable, skip or loosen a PCA check to make a test or a request pass; fix the action mapping, the audience or the grant instead.',
  'Keys, state directories and audit logs are never committed. Never write key material yourself: the apply command generates it, gitignored, mode 0600.',
  'A grant, an allow or a limit that was learned from traffic is a proposal. A human signs it (pca autopilot review --yes); a coding agent never signs for them.',
  'Do not mark a tool as allow/read because its name sounds harmless. Ask the human which tools only read.',
];

const HUMAN = /\b(sign|review|decide|enforce|pin)\b/i;
const sha = (s: string): string => createHash('sha256').update(s).digest('hex');

/** Reshape `pca init`'s plan into structured steps. */
export function fromInitPlan(p: InitPlan, integration: Integration, language: Language | null): Plan {
  const steps: PlanStep[] = [];
  const apply = `npx @atlasauth/pca-cli init${p.proxy ? ' --proxy' : ''}${p.mode === 'enforce' ? ' --mode enforce' : ''} --yes`;
  steps.push({ id: 'apply', kind: 'command', command: apply, title: 'Apply the plan below with one command', why: 'pca init writes every change listed here, generates the dev key (gitignored, 0600, never printed) and refuses on a dirty git tree. You may instead apply the listed file steps yourself, except key files.' });
  for (const c of p.changes) {
    if (c.generated !== undefined) {
      steps.push({ id: `change:${c.path}`, kind: 'create', path: c.path, title: `Create ${c.path} (generated)`, why: `${c.why}. Generated by the apply command only: never write or print key material yourself.`, appliedBy: 'apply' });
      continue;
    }
    steps.push({ id: `change:${c.path}`, kind: c.before === null ? 'create' : 'edit', path: c.path, title: `${c.before === null ? 'Create' : 'Edit'} ${c.path}`, why: c.why, content: c.after, ...(c.before !== null ? { beforeDigest: sha(c.before) } : {}), appliedBy: 'apply' });
  }
  p.install.forEach((cmd, i) => steps.push({ id: `install:${i}`, kind: 'command', command: cmd, title: 'Install the dependencies', why: 'After the changes above.' }));
  p.snippets.forEach((s, i) => steps.push({ id: `snippet:${i}`, kind: 'edit', path: s.where, title: s.title, why: `Paste at: ${s.where}`, content: s.code }));
  p.nextSteps.forEach((t, i) => {
    const [first, ...rest] = t.split('\n');
    steps.push({ id: `next:${i + 1}`, kind: 'decision', title: first ?? t, why: rest.map((l) => l.trim()).filter(Boolean).join('\n') || 'See the pca init guide.', ...(HUMAN.test(t) ? { human: true } : {}) });
  });
  return {
    integration,
    language,
    mode: p.mode,
    steps,
    notes: p.notes,
    blockers: p.blockers,
    dirty: p.dirty,
    verify: ['npx @atlasauth/pca-cli init --check', 'pca_doctor (this server) or: npx @atlasauth/pca-doctor --url <DEPLOYMENT_URL>'],
    rules: RULES,
    docs: ['guides/add-pca-in-one-command.md', 'guides/framework-recipes.md', 'guides/mcp-quickstart.md', 'reference/refusals.md'],
  };
}

/** The default planner: `pca init`'s own `makePlan` (a dry run: it reads the project and git status, writes nothing). */
export function initPlanner(deps: InitDeps = realDeps): Planner {
  return async (root, d, o) => {
    const integration = o.integration ?? d.recommendation.integration;
    const proxy = integration !== 'sdk-guard';
    try {
      const plan = await makePlan({ cwd: root, proxy, yes: false, dryRun: true, force: false, check: false, noImport: false, ...(o.namespace ? { ns: o.namespace } : {}), ...(o.mode ? { mode: o.mode } : {}) }, deps);
      return fromInitPlan(plan, integration, d.primaryLanguage);
    } catch (e) {
      if (e instanceof InitError) throw new Error(e.message);
      throw e;
    }
  };
}
