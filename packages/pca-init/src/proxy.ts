/**
 * `pca init --proxy`: the zero-code path. One pca-proxy config per MCP server (or one for the HTTP service), in observe mode, plus the
 * single command that runs it. Nothing about the app changes. The config is validated with the proxy's own parser before it is written.
 */
import { stringify } from 'yaml';
import { routesOf } from './imports';
import type { Detection, FileChange } from './types';

export interface ProxyPlan {
  changes: FileChange[];
  /** Exact commands to run, one per config. */
  commands: string[];
  notes: string[];
}

export class ProxyError extends Error {}

const KEY_ENV = 'PCA_PRINCIPAL_KEY';
const nsOf = (s: string): string => {
  const n = s.toLowerCase().replace(/[^a-z0-9_]+/g, '_').replace(/^[^a-z]+/, '').replace(/_+$/, '').slice(0, 32);
  return n.length > 0 ? n : 'mcp';
};

async function validate(path: string, text: string): Promise<void> {
  const { parseConfigText } = await import('@atlasauth/pca-proxy');
  try {
    parseConfigText(text, 'yaml');
  } catch (e) {
    throw new ProxyError(`internal: the generated ${path} is not a valid pca-proxy config: ${e instanceof Error ? e.message : String(e)}`);
  }
}

export async function planProxy(d: Detection, o: { ns: string; server?: string; upstream?: string; read: (rel: string) => string | null }): Promise<ProxyPlan> {
  const common = { mode: 'observe', agent: { principalKeyEnv: KEY_ENV }, state: { backend: 'file', dir: '.pca/proxy-state' }, audit: { path: '.pca/proxy-audit.jsonl' } };
  const changes: FileChange[] = [];
  const commands: string[] = [];
  const notes: string[] = [];
  const emit = async (rel: string, doc: object, why: string, cmd: string): Promise<void> => {
    const after = `# Generated by \`pca init --proxy\`. mode: observe forwards everything and records what enforce mode would refuse.\n${stringify(doc)}`;
    await validate(rel, after);
    changes.push({ path: rel, before: o.read(rel), after, why });
    commands.push(cmd);
  };

  let servers = d.mcpServers;
  if (o.server !== undefined) {
    servers = servers.filter((s) => s.name === o.server);
    if (servers.length === 0) throw new ProxyError(`--server ${o.server}: no MCP server of that name (found: ${d.mcpServers.map((s) => s.name).join(', ') || 'none'})`);
  }
  if (servers.length > 0) {
    for (const s of servers) {
      const rel = servers.length === 1 ? 'pca-proxy.yaml' : `pca-proxy.${s.name}.yaml`;
      const ns = nsOf(s.name);
      const mcp = { ns, upstream: s.command !== undefined ? { command: s.command, ...(s.args && s.args.length > 0 ? { args: s.args } : {}) } : { url: s.url! } };
      if (s.envNames.length > 0) notes.push(`${s.name}: its environment variables (${s.envNames.join(', ')}) are not copied; the proxy passes your shell environment through, so export them where you run it`);
      if (s.url !== undefined) notes.push(`${s.name}: a remote server's request headers are not copied; add them under mcp.upstream.headers using \${NAME} so the secret stays in your environment`);
      await emit(rel, { ...common, audience: ns, agent: { ...common.agent, goal: `use ${s.name} through the pca-proxy` }, mcp }, `a pca-proxy in front of the MCP server '${s.name}' (from ${s.source})`, `${KEY_ENV}="$(cat .pca/dev.key)" npx @atlasauth/pca-proxy mcp --config ${rel}`);
    }
    return { changes, commands, notes };
  }

  // an HTTP service
  const openapi = d.openapi;
  const routes = openapi === null ? routesOf(d) : [];
  if (openapi === null && routes.length === 0) {
    throw new ProxyError('--proxy: no MCP server definition (.mcp.json, mcp.json, .cursor/mcp.json, .vscode/mcp.json), OpenAPI file or route found to put the proxy in front of. Add one of them, or write pca-proxy.yaml by hand (npx @atlasauth/pca-proxy init mcp -- COMMAND).');
  }
  const upstream = o.upstream ?? `http://127.0.0.1:${d.port}`;
  // a route starts as `approve`: a human decides; the dangerous default is a write
  const http = {
    upstream,
    listen: { host: '127.0.0.1', port: 8788 },
    mode: 'sidecar',
    ns: o.ns,
    ...(openapi !== null ? { openapi } : { routes: routes.map((r) => ({ method: r.method.toUpperCase(), path: r.path, policy: 'approve', effect: r.method === 'get' ? 'read' : 'write' })) }),
  };
  await emit('pca-proxy.yaml', { ...common, audience: o.ns, agent: { ...common.agent, goal: `call ${d.ns} through the pca-proxy` }, http }, `a pca-proxy in front of the HTTP service at ${upstream}${openapi !== null ? ` (operations from ${openapi})` : ` (${routes.length} routes read from the source)`}`, `${KEY_ENV}="$(cat .pca/dev.key)" npx @atlasauth/pca-proxy http --config pca-proxy.yaml`);
  notes.push(`point your callers at http://127.0.0.1:8788 instead of ${upstream}; ${openapi !== null ? 'each operation is mapped from the OpenAPI file' : 'each route starts as policy approve until you decide which are safe to allow'}`);
  return { changes, commands, notes };
}
