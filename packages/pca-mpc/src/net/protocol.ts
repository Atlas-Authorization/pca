const DEFAULT_Q = 100;

/** Number of independent circuit chains (= output bits = input bits per owner). */
export const chainCount = (Q: number): number => 1 + T_M + Q;

/** Test-only protocol-level misbehaviour for a (malicious) party. Never set in production. */
export interface Behavior {
  kind:
    | 'open-lie' //          add a delta to my broadcast value share in `round` (the pairwise tag exposes it; else the MAC-check)
    | 'mac-lie' //           corrupt my MAC share in the batched check (MAC-check must catch it; blame round names me)
    | 'bad-tag' //           send a wrong pairwise tag for my opened share in `round`
    | 'sigma-lie' //         commit to and open a MAC residual share that is off by one (consistent with my commitment)
    | 'offline-lie' //       [no-dealer] feed a wrong operand into the first triple-product OT multiplication (the sacrifice must catch it)
    | 'ot-u-lie' //          [no-dealer] send an inconsistent OT-extension u matrix (the KOS check must catch it and name me)
    | 'ot-proof-lie' //      [no-dealer] send a base-OT Schnorr proof that does not verify (the receiver must abort and name me)
    | 'equivocate' //        send DIFFERENT value shares to different peers in `round`
    | 'bad-coin-open' //     open a coin seed that does not match my commitment
    | 'bad-sigma-open' //    open a MAC residual that does not match my commitment
    | 'short-array' //       send a wrong-length array in `round`
    | 'noncanonical' //      send a non-canonical field element (>= p) in `round`
    | 'crash' //             exit the process abruptly when reaching `round`
    | 'silent'; //           stay connected but stop participating at `round` (peers must time out)
  round?: string;
}

