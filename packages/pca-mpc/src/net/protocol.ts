export interface PartyConfig {
  id: number;
  n: number;
  Q?: number;
  input: DecisionVector;
  mesh: Mesh;
  /** Node id of the dealer (default n). */
  dealerId?: number;
  /** Which offline phase to run (default `no-dealer`: the parties generate everything from OT). `trusted-dealer` also needs `insecureTrustedDealer: true`. */
  offline?: 'trusted-dealer' | 'no-dealer';
  /** Explicit opt-in to the trusted-dealer offline phase: one process then sees every share and MAC key. Refused otherwise. */
  insecureTrustedDealer?: boolean;
  /** TEST ONLY: refused unless `unsafeTestHooks` is `true`. */
  behavior?: Behavior;
  /** Explicit opt-in for `behavior`. Leave unset in production. */
  unsafeTestHooks?: boolean;
  sessionId: string;
  /** Deadline (ms) every party has to commit to and open its forensic disclosure; shared by all parties (default 30 s). */
  forensicDeadlineMs?: number;
}

interface Opened {
  val: bigint;
  /** My MAC share (with its pairwise tags/keys) under each key, as used at this opening. */
  mac: PA[];
}

const sha = (...parts: (string | Buffer)[]): Buffer => {
  const h = createHash('sha256');
  for (const p of parts) {
    h.update(typeof p === 'string' ? Buffer.from(p) : p);
    h.update(Buffer.from([0]));
  }
  return h.digest();
};

/** Uniform non-zero field element `j` of the public challenge stream `label` derived from `seed` (rejection on p). */
function challenge(seed: Buffer, label: string, j: number): bigint {
  for (let ctr = 0; ; ctr++) {
    const h = sha('chal', seed, `${label}:${j}:${ctr}`);
    const x = h.readBigUInt64BE(0) & ((1n << 61n) - 1n);
    if (x < PRIME && x !== 0n) return x;
  }
}

export async function runParty(cfg: PartyConfig): Promise<PartyResult> {
  const { id, n, mesh, sessionId } = cfg;
  const Q = cfg.Q ?? DEFAULT_Q;
  const dealerId = cfg.dealerId ?? n;
  const offlineMode = cfg.offline ?? 'no-dealer';
  if (offlineMode === 'trusted-dealer' && cfg.insecureTrustedDealer !== true) {
    throw new NetAbort('local', null, id, "offline 'trusted-dealer' requires insecureTrustedDealer: true (the dealer sees every share and key); the default is 'no-dealer'");
  }
  const C = chainCount(Q);
  const K = MAC_KEYS;
  const P = SACRIFICE_PARTNERS;
  if (cfg.behavior && cfg.unsafeTestHooks !== true) {
    throw new NetAbort('local', null, id, 'the behavior test hook requires unsafeTestHooks: true (test-only)');
  }
  const beh = cfg.behavior;
  const t0 = performance.now();
  const rounds: RoundStat[] = [];
  const transcript = createHash('sha256');
  const others: number[] = [];
  for (let i = 0; i < n; i++) if (i !== id) others.push(i);

  if (!Number.isInteger(n) || n < 1) throw new NetAbort('local', null, id, 'n must be >= 1');
  const v = cfg.input;
  if (![0, 1].includes(v.allow) || ![1, 2, 3].includes(v.t) || !Number.isInteger(v.rQuant) || v.rQuant < 0 || v.rQuant > Q) {
    throw new NetAbort('local', null, id, 'invalid decision vector');
  }

  const totals = (): { out: number; in: number } => {
    let o = 0;
    let i = 0;
    for (const s of mesh.stats()) {
      o += s.appBytesOut;
      i += s.appBytesIn;
    }
    return { out: o, in: i };
  };

  const crashIf = (rd: string): void => {
    if (beh?.kind === 'crash' && beh.round === rd) process.exit(7);
    if (beh?.kind === 'silent' && beh.round === rd) throw new SilentParty();
  };

  /**
   * One all-to-all round among the parties: send `mine(peer)` to each peer, collect + validate theirs.
   * `hashed = false` keeps a round (the peer-specific pairwise tags) out of the echoed transcript.
   */
  async function exchange<T>(
    rd: string,
    mine: (peer: number) => unknown,
    parse: (p: number, raw: unknown) => T,
    common: unknown,
    hashed = true,
    timeoutMs?: number,
  ): Promise<Map<number, T>> {
    crashIf(rd);
    const a = totals();
    const s = performance.now();
    for (const p of others) mesh.send(p, rd, mine(p));
    const raw = await mesh.collect(rd, others, timeoutMs);
    const parsed = new Map<number, T>();
    for (const p of others) {
      try {
        parsed.set(p, parse(p, raw.get(p)));
      } catch (e) {
        if (e instanceof NetAbort) {
          mesh.fail(e);
          throw e;
        }
        const ne = new NetAbort('malformed', p, id, `round '${rd}': ${(e as Error).message}`);
        mesh.fail(ne);
        throw ne;
      }
    }
    if (hashed) {
      // transcript: party order, canonical JSON of what each party broadcast in this round
      transcript.update(rd);
      for (let p = 0; p < n; p++) {
        transcript.update(`|${p}:`);
        transcript.update(JSON.stringify(p === id ? common : raw.get(p)));
      }
    }
    const b = totals();
    rounds.push({ rd, ms: performance.now() - s, bytesOut: b.out - a.out, bytesIn: b.in - a.in });
    return parsed;
  }

  const bad = (p: number, what: string): never => {
    throw new NetAbort('malformed', p, id, what);
  };
  const arr = (p: number, raw: unknown, len: number): bigint[] => unhxArray(raw, len) ?? bad(p, `expected ${len} canonical field elements`);
  const abort = (e: NetAbort): never => {
    mesh.fail(e);
    throw e;
  };

  // ---- offline phase: prep from the trusted dealer, or the OT-based no-dealer phase ----
  
  let prep: Prep;
  crashIf('prep');
  const prepStart = performance.now();
  const before = totals();
  if (offlineMode === 'trusted-dealer') {
    prep = await receiveDealerPrep();
  } else {
    const { runOfflineNet } = await import('./offline-net');
    prep = await runOfflineNet({ mesh, id, n, C, keys: K, partners: P, sessionId, input: v, Q, behavior: beh, exchange: (rd, mine, parse) => exchange(rd, mine, parse, null, false), crashIf, bad, arr });
  }
  const afterPrep = totals();
  rounds.push({ rd: 'prep', ms: performance.now() - prepStart, bytesOut: afterPrep.out - before.out, bytesIn: afterPrep.in - before.in });

  async function receiveDealerPrep(): Promise<Prep> {
    const lay = prepLayout(n, C, K, P, true);
    const first = (await mesh.recv(dealerId, 'prep')) as { total?: unknown; chunks?: unknown; nums?: unknown } | null;
    let nums: bigint[] = [];
    try {
      if (typeof first?.total !== 'number' || first.total !== lay.nums) bad(dealerId, 'bad prep size');
      if (typeof first?.chunks !== 'number' || first.chunks !== Math.max(1, Math.ceil(lay.nums / PREP_CHUNK))) bad(dealerId, 'bad prep chunk count');
      const take = (raw: unknown, len: number): bigint[] => unhxArray(raw, len) ?? bad(dealerId, 'bad prep numbers');
      nums = take(first?.nums, Math.min(PREP_CHUNK, lay.nums));
      for (let c = 1; c < (first?.chunks as number); c++) {
        const part = (await mesh.recv(dealerId, `prep.${c}`)) as unknown;
        nums = nums.concat(take(part, Math.min(PREP_CHUNK, lay.nums - c * PREP_CHUNK)));
      }
    } catch (e) {
      const ne = e instanceof NetAbort ? e : new NetAbort('malformed', dealerId, id, (e as Error).message);
      return abort(ne);
    }
    let o = 0;
    const delta = nums[o++]!;
    if (delta === 0n) return abort(new NetAbort('dealer', dealerId, id, 'the dealer gave me a zero verification key'));
    const w = paWidth(n, true);
    const alpha: PA[] = [];
    for (let l = 0; l < K; l++) {
      alpha.push(paParse(nums, o, id, n, true));
      o += w;
    }
    const aw = awWidth(n, K, true);
    const triples: AW[][] = [];
    for (let t = 0; t < lay.triples; t++) {
      const sh: AW[] = [];
      for (let s = 0; s < sharingsPerTriple(P); s++) {
        sh.push(awParse(nums, o, id, n, K, true));
        o += aw;
      }
      triples.push(sh);
    }
    const inputs: AW[] = [];
    for (let q = 0; q < lay.inputs; q++) {
      inputs.push(awParse(nums, o, id, n, K, true));
      o += aw;
    }
    const myPlain = nums.slice(o, o + C);
    return { mode: 'trusted-dealer', tagged: true, delta, alpha, triples, inputs, myPlain };
  }

  const env: PaEnv = { id, n, delta: prep.delta, tagged: prep.tagged };
  const addPub = (x: AW, c: bigint): AW => wAddPublic(env, x, c, prep.alpha);
  const not = (x: AW): AW => addPub(wNeg(x), 1n);

  // ---- retained for the MAC-check / blame: every opened value, with my MAC shares at that opening ----
  const opened: Opened[] = [];

  /** Open authenticated values: broadcast value shares, verify pairwise tags (dealer mode), record for the MAC-check. */
  async function openMany(rd: string, ws: AW[]): Promise<bigint[]> {
    let sendVals = ws.map((x) => x.v.x);
    const macs = ws.map((x) => x.m);
    if (beh?.round === rd) {
      if (beh.kind === 'open-lie') sendVals = sendVals.map((x, i) => (i === 0 ? fadd(x, 1n) : x));
      if (beh.kind === 'mac-lie') macs[0] = macs[0]!.map((pa, l) => (l === 0 ? { ...pa, x: fadd(pa.x, 1n) } : pa));
    }
    const common = sendVals.map(hx);
    const mineFn = (peer: number): unknown => {
      if (beh?.kind === 'equivocate' && beh.round === rd && peer === others[0]) {
        return common.map((s, i) => (i === 0 ? hx(fadd(BigInt('0x' + s), 1n)) : s));
      }
      if (beh?.kind === 'short-array' && beh.round === rd) return common.slice(1);
      if (beh?.kind === 'noncanonical' && beh.round === rd) return common.map((s, i) => (i === 0 ? hx(PRIME) : s));
      return common;
    };
    const got = await exchange(rd, mineFn, (p, raw) => arr(p, raw, ws.length), common);
    if (prep.tagged) {
      // pairwise tags: peer-specific, so a separate un-echoed round; each receiver verifies at once
      const tagMsg = (peer: number): unknown =>
        ws.map((x, i) => hx(beh?.kind === 'bad-tag' && beh.round === rd && i === 0 ? fadd(x.v.tag[peer]!, 1n) : x.v.tag[peer]!));
      const tags = await exchange(`${rd}.t`, tagMsg, (p, raw) => arr(p, raw, ws.length), null, false);
      for (const p of others) {
        for (let i = 0; i < ws.length; i++) {
          if (!paVerify(env, ws[i]!.v, p, got.get(p)![i]!, tags.get(p)![i]!)) {
            return abort(
              new NetAbort(
                'mac-check',
                p,
                id,
                `pairwise MAC on party ${p}'s opened share failed in round '${rd}' (index ${i}): the share or its tag is not what the dealer issued`,
              ),
            );
          }
        }
      }
    }
    const out: bigint[] = [];
    for (let i = 0; i < ws.length; i++) {
      let sum = sendVals[i]!;
      for (const p of others) sum = fadd(sum, got.get(p)![i]!);
      out.push(sum);
      opened.push({ val: sum, mac: macs[i]! });
    }
    return out;
  }

  // ---- coin flip (commit / open of a random seed) -> a joint public seed ----
  async function coin(label: string, tamperOpen: boolean): Promise<Buffer> {
    const mySeed = randomBytes(32);
    const seedCommit = sha('seed', sessionId, label, String(id), mySeed).toString('hex');
    const seedCommits = await exchange(
      `${label}-c`,
      () => seedCommit,
      (p, raw) => (typeof raw === 'string' && /^[0-9a-f]{64}$/.test(raw) ? raw : bad(p, 'bad commitment')),
      seedCommit,
    );
    const openSeedMsg = (): string => (tamperOpen && beh?.kind === 'bad-coin-open' ? randomBytes(32).toString('hex') : mySeed.toString('hex'));
    const seeds = await exchange(
      `${label}-o`,
      openSeedMsg,
      (p, raw) => {
        if (typeof raw !== 'string' || !/^[0-9a-f]{64}$/.test(raw)) return bad(p, 'bad seed');
        const sd = Buffer.from(raw, 'hex');
        if (sha('seed', sessionId, label, String(p), sd).toString('hex') !== seedCommits.get(p)) {
          throw new NetAbort('commitment', p, id, `party ${p} opened a coin seed that does not match its commitment`);
        }
        return sd;
      },
      mySeed.toString('hex'),
    );
    return sha('joint', sessionId, label, ...Array.from({ length: n }, (_, p) => (p === id ? mySeed : seeds.get(p)!)));
  }

  // ---- sacrifice: certify every triple against its partners before it is used ----
  const nT = prep.triples.length;
  if (nT > 0) {
    const joint1 = await coin('coin1', false);
    const rhoW: AW[] = [];
    const idx = (t: number, r: number): number => t * P + r;
    for (let t = 0; t < nT; t++) {
      const [a, , , ...parts] = prep.triples[t]!;
      for (let r = 0; r < P; r++) {
        const e = challenge(joint1, 'sac', idx(t, r));
        rhoW.push(wSub(wScale(a!, e), parts[2 * r]!));
      }
    }
    const rho = await openMany('sac-rho', rhoW);
    const tauW: AW[] = [];
    for (let t = 0; t < nT; t++) {
      const [, b, c, ...parts] = prep.triples[t]!;
      for (let r = 0; r < P; r++) {
        const e = challenge(joint1, 'sac', idx(t, r));
        tauW.push(wSub(wSub(wScale(c!, e), parts[2 * r + 1]!), wScale(b!, rho[idx(t, r)]!)));
      }
    }
    const tau = await openMany('sac-tau', tauW);
    const badAt = tau.findIndex((x) => x !== 0n);
    if (badAt >= 0) {
      // Dealer-free mode: the triple is discarded, so its OT transcript can be disclosed and audited to name a party
      // that fed a wrong operand into a triple product (forensics.ts). Every honest party reaches this point together.
      let attributed: number | null = null;
      let note = '';
      const fx = prep.mode === 'no-dealer' ? prep.forensics : undefined;
      if (fx) {
        const bt = Math.floor(badAt / P);
        const mine = fx.disclose(bt);
        // R3-17: commit first, open only once every commitment is in hand (forensics.ts); a late or absent party times out at the shared deadline.
        const got = await exchangeDisclosures({
          sessionId,
          id,
          n,
          tripleIndex: bt,
          mine,
          slots: fx.slots,
          rows: fx.rows,
          deadlineMs: cfg.forensicDeadlineMs ?? DEFAULT_FORENSIC_DEADLINE_MS,
          exchange: (rd, m, parse, t) => exchange(rd, m, parse, null, false, t),
          bad: (p, what) => bad(p, what),
        });
        const all = new Map<number, Disclosure>([[id, mine]]);
        for (const [p, d] of got) all.set(p, d);
        const res = auditDisclosures(all, fx.gadget);
        attributed = blameFrom(id, res);
        note =
          attributed === null
            ? ` (OT transcript audit: ${res.pairBad.length} inconsistent pair(s), no party can be named from this view: a pair failure between two other parties is not evidence against either of them to me)`
            : ` (OT transcript audit names party ${attributed})`;
      }
      // every honest tag already verified, so the opened tau are the true ones: the dealt triple is wrong.
      return abort(
        new NetAbort(
          prep.mode === 'trusted-dealer' ? 'dealer' : 'mac-check',
          prep.mode === 'trusted-dealer' ? dealerId : (attributed ?? (n === 2 ? 1 - id : null)),
          id,
          `triple sacrifice FAILED at triple ${Math.floor(badAt / P)} (partner ${badAt % P}): c != a*b in the offline material; aborting with no output${note}`,
          undefined,
          undefined,
          { reason: 'the triple sacrifice failed in dealer-free mode and the OT transcript audit of this party\'s own view names no one (a failing pair that does not involve me is not evidence I can use, and an accusation is never accepted against a third party)' },
        ),
      );
    }
  }

  // ---- inputs: bit k of owner o is the C-vector [allow, t-therm(3), r-therm(Q)] ----
  const myBits = [v.allow, ...thermometerEncode(v.t, T_M), ...thermometerEncode(v.rQuant, Q)];
  let bitShare: (owner: number, k: number) => AW;
  if (prep.mode === 'trusted-dealer') {
    const masked = myBits.map((b, k) => fsub(BigInt(b), prep.myPlain[k]!));
    const maskedMsg = masked.map(hx);
    const gotMasked = await exchange(
      'inputs',
      () => maskedMsg,
      (p, raw) => arr(p, raw, C),
      maskedMsg,
    );
    bitShare = (owner, k) => {
      const pub = owner === id ? masked[k]! : gotMasked.get(owner)![k]!;
      return addPub(prep.inputs[owner * C + k]!, pub);
    };
  } else {
    // No-dealer: the inputs are already authenticated sharings of the bits. Run the MASCOT input-consistency
    // check: open a random masked combination (the opening joins the batched MAC-check below).
    bitShare = (owner, k) => prep.inputs[owner * C + k]!;
    const jointIn = await coin('coin-in', false);
    let w = prep.checkMask!;
    for (let q = 0; q < n * C; q++) w = wAdd(w, wScale(prep.inputs[q]!, challenge(jointIn, 'in', q)));
    await openMany('in-check', [w]);
  }

  // ---- chains: acc_c over owners; allow uses AND, others OR(=NOT AND NOT) ----
  const isOr = (c: number): boolean => c !== 0;
  let acc: AW[] = [];
  for (let c = 0; c < C; c++) {
    const b0 = bitShare(0, c);
    acc.push(isOr(c) ? not(b0) : b0);
  }

  let mults = 0;
  for (let s = 1; s < n; s++) {
    const trs = Array.from({ length: C }, (_, c) => prep.triples[(s - 1) * C + c]!);
    const ys = Array.from({ length: C }, (_, c) => {
      const b = bitShare(s, c);
      return isOr(c) ? not(b) : b;
    });
    const ds = acc.map((x, c) => wSub(x, trs[c]![0]!));
    const es = ys.map((y, c) => wSub(y, trs[c]![1]!));
    const pub = await openMany(`mul${s - 1}`, [...ds, ...es]);
    acc = acc.map((_, c) => {
      const d = pub[c]!;
      const e = pub[C + c]!;
      const [ta, tb, tc] = trs[c]! as [AW, AW, AW];
      let z = wAdd(tc, wAdd(wScale(tb, d), wScale(ta, e)));
      z = addPub(z, fmul(d, e));
      return z;
    });
    mults += C;
  }

  // ---- outputs: allow as-is; or-chains are NOT of the product ----
  const outShares = acc.map((x, c) => (isOr(c) ? not(x) : x));
  const outVals = await openMany('out', outShares);

  // ---- MAC-check: coin-flip for the challenges, one independent challenge vector per key ----
  const joint = await coin('coin', true);
  const chal = (l: number, j: number): bigint => challenge(joint, `mac${l}`, j);
  const aPub: bigint[] = [];
  for (let l = 0; l < K; l++) {
    let a = 0n;
    opened.forEach((o, j) => {
      a = fadd(a, fmul(chal(l, j), o.val));
    });
    aPub.push(a);
  }
  const gammaOf = (l: number): bigint => {
    let g = 0n;
    opened.forEach((o, j) => {
      g = fadd(g, fmul(chal(l, j), o.mac[l]!.x));
    });
    return g;
  };
  const Gamma = Array.from({ length: K }, (_, l) => gammaOf(l));
  const sigma = Gamma.map((g, l) => fsub(g, fmul(prep.alpha[l]!.x, aPub[l]!)));
  const sigNonce = randomBytes(32);
  const sigCommit = (p: number, s: bigint[], nonce: Buffer): string => sha('sigma', sessionId, String(p), s.map(hx).join(','), nonce).toString('hex');
  const sigmaSent = beh?.kind === 'sigma-lie' ? sigma.map((s, l) => (l === 0 ? fadd(s, 1n) : s)) : sigma;
  const mySigCommit = sigCommit(id, sigmaSent, sigNonce);
  const sigCommits = await exchange(
    'sig-c',
    () => mySigCommit,
    (p, raw) => (typeof raw === 'string' && /^[0-9a-f]{64}$/.test(raw) ? raw : bad(p, 'bad commitment')),
    mySigCommit,
  );
  const mySigOpen = { s: sigmaSent.map(hx), nonce: sigNonce.toString('hex') };
  const sigOpens = await exchange(
    'sig-o',
    () => (beh?.kind === 'bad-sigma-open' ? { s: sigmaSent.map((s, l) => hx(l === 0 ? fadd(s, 1n) : s)), nonce: mySigOpen.nonce } : mySigOpen),
    (p, raw) => {
      const o = raw as { s?: unknown; nonce?: unknown } | null;
      const sv = unhxArray(o?.s, K);
      if (sv === null || typeof o?.nonce !== 'string' || !/^[0-9a-f]{64}$/.test(o.nonce)) return bad(p, 'bad sigma opening');
      if (sigCommit(p, sv, Buffer.from(o.nonce, 'hex')) !== sigCommits.get(p)) {
        throw new NetAbort('commitment', p, id, `party ${p} opened a MAC residual that does not match its commitment`);
      }
      return sv;
    },
    mySigOpen,
  );
  const residual = Array.from({ length: K }, (_, l) => {
    let r = sigmaSent[l]!;
    for (const p of others) r = fadd(r, sigOpens.get(p)![l]!);
    return r;
  });
  const macFailed = residual.some((r) => r !== 0n);

  // ---- transcript echo: everyone must have seen the same broadcasts (also fixes the sigma data for the blame) ----
  const digest = transcript.copy().digest('hex');
  const digests = await exchange(
    'digest',
    () => digest,
    (p, raw) => (typeof raw === 'string' && /^[0-9a-f]{64}$/.test(raw) ? raw : bad(p, 'bad digest')),
    digest,
  );
  for (const p of others) {
    if (digests.get(p) !== digest) {
      return abort(new NetAbort('equivocation', p, id, `transcript digest of party ${p} differs from mine (a broadcast was inconsistent)`));
    }
  }

  if (macFailed) {
    const msg = 'MAC-check FAILED: an opened value or MAC share was inconsistent; aborting with no output';
    if (!prep.tagged) {
      // No pairwise tags in this mode: the evidence cannot name a party, except in the two-party case.
      return abort(new NetAbort('mac-check', n === 2 ? 1 - id : null, id, msg, undefined, undefined, { reason: 'this mode carries no pairwise tags, so a MAC-check failure cannot name a party (only possible with two parties)' }));
    }
    // ---- blame: every party opens its combined MAC shares with their pairwise tags; each verifier checks them ----
    const combo = (l: number, pick: (o: Opened) => bigint): bigint => {
      let g = 0n;
      opened.forEach((o, j) => {
        g = fadd(g, fmul(chal(l, j), pick(o)));
      });
      return g;
    };
    const blameMsg = (peer: number): unknown => ({
      g: Gamma.map(hx),
      gt: Array.from({ length: K }, (_, l) => hx(combo(l, (o) => o.mac[l]!.tag[peer]!))),
      a: prep.alpha.map((a) => hx(a.x)),
      at: prep.alpha.map((a) => hx(a.tag[peer]!)),
    });
    // Abort claims arriving during this round are read in link order (see Mesh.setDeferAborts): the cheater's own abort
    // must not pre-empt an honest party that has not yet received every peer's blame data.
    mesh.setDeferAborts(true);
    const blames = await exchange(
      'blame',
      blameMsg,
      (p, raw) => {
        const o = raw as { g?: unknown; gt?: unknown; a?: unknown; at?: unknown } | null;
        return { g: arr(p, o?.g, K), gt: arr(p, o?.gt, K), a: arr(p, o?.a, K), at: arr(p, o?.at, K) };
      },
      null,
      false,
    ).finally(() => mesh.setDeferAborts(false));
    for (const p of others) {
      const b = blames.get(p)!;
      for (let l = 0; l < K; l++) {
        const keyCombo = combo(l, (o) => o.mac[l]!.key[p]!);
        if (fadd(keyCombo, fmul(env.delta, b.g[l]!)) !== b.gt[l]!) {
          return abort(new NetAbort('mac-check', p, id, `${msg} - party ${p}'s MAC share (key ${l}) does not match its pairwise tag`));
        }
        if (fadd(prep.alpha[l]!.key[p]!, fmul(env.delta, b.a[l]!)) !== b.at[l]!) {
          return abort(new NetAbort('mac-check', p, id, `${msg} - party ${p}'s key share (key ${l}) does not match its pairwise tag`));
        }
        if (fsub(b.g[l]!, fmul(b.a[l]!, aPub[l]!)) !== sigOpens.get(p)![l]!) {
          return abort(new NetAbort('mac-check', p, id, `${msg} - party ${p}'s opened MAC residual (key ${l}) is not what its authenticated shares give`));
        }
      }
    }
    // Every other party's data is consistent with its pairwise tags; so is mine: the offline material disagrees.
    if (prep.mode === 'trusted-dealer') {
      return abort(new NetAbort('dealer', dealerId, id, `${msg} - every party's shares verify, so the trusted dealer's MACs are inconsistent with its values`));
    }
    return abort(
      new NetAbort('mac-check', n === 2 ? 1 - id : null, id, `${msg} - every party's shares verify under its pairwise tags, so the offline material is inconsistent (a wrong OT operand): not attributable`, undefined, undefined, { reason: 'every party\'s shares verify under its pairwise tags, so the failure is in the offline OT material and no party can be named' }),
    );
  }

  // ---- only now decode ----
  const bit = (x: bigint): 0 | 1 => (x === 1n ? 1 : 0);
  const allow = bit(outVals[0]!);
  const tBits = outVals.slice(1, 1 + T_M).map(bit);
  const rBits = outVals.slice(1 + T_M).map(bit);
  const composed: ComposedDecision = {
    allow,
    t: Math.min(3, Math.max(1, thermometerDecode(tBits))) as 1 | 2 | 3,
    rQuant: thermometerDecode(rBits),
  };
  await mesh.finish();
  return {
    id,
    n,
    Q,
    composed,
    rounds,
    transcriptDigest: digest,
    wallMs: performance.now() - t0,
    multiplications: mults,
    opens: opened.length,
    offlineMode: prep.mode,
    macKeys: K,
    sacrificedTriples: nT,
    sacrificePartners: P,
    identifiableAbort: prep.tagged,
  };
}
