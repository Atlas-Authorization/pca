/**
 * The DISTRIBUTED malicious-with-abort (SPDZ-style) composition protocol (research prototype).
 *
 * Same circuit and semantics as `composeSecureMalicious` (allow = AND, t = MAX, r = MAX via
 * thermometers; authenticated Beaver multiplication; batched MAC-check before any output), but each
 * party is its OWN process holding ONLY its own shares, and every opening is a real message over the
 * TLS mesh (`mesh.ts`). Rounds (n parties, C = 1 + 3 + Q independent chains, k = MAC_KEYS global keys):
 *
 *   prep     dealer  -> party   : [TRUSTED-DEALER mode] key shares, sacrificed-triple material, input masks, pairwise tags
 *            (or, in NO-DEALER mode, the OT-based offline phase of `offline-net.ts` runs here instead)
 *   coin1-*  all-to-all         : commit/open of a random seed -> public challenges for the triple sacrifice
 *   sac-rho  all-to-all         : value shares of rho = e*a - a-hat for every triple and sacrifice partner
 *   sac-tau  all-to-all         : value shares of tau = e*c - c-hat - rho*b; every tau must be 0
 *   inputs   all-to-all         : [dealer mode] owner broadcasts x - r  (r is the owner's dealer-given mask)
 *   in-check all-to-all         : [no-dealer mode] opening of a masked random combination of the inputs
 *   mul0..   all-to-all         : value shares of d = x-a, e = y-b for all C chains at once (n-1 rounds)
 *   out      all-to-all         : value shares of the C output bits
 *   <rd>.t   all-to-all         : [dealer mode] after every opening, the pairwise tags: each receiver verifies
 *                                 the sender's opened shares IMMEDIATELY and blames the sender if one fails
 *   coin-c/o all-to-all         : commit/open of a random seed -> public MAC-check challenges
 *   sig-c/o  all-to-all         : commit/open of each party's MAC residual shares (one per key); sums must be 0
 *   digest   all-to-all         : hash of the whole broadcast transcript; any disagreement aborts
 *   blame    all-to-all         : [only after a failed MAC-check, dealer mode] every party opens its combined MAC
 *                                 shares and key shares with their pairwise tags; each verifier checks them and
 *                                 names the party whose data is inconsistent (or the dealer, if none is)
 *
 * No output is decoded until the MAC-check and the transcript echo pass. Everything else (timeouts,
 * malformed/duplicate/out-of-order frames, disconnects, aborts) is handled by the mesh.
 *
 * OFFLINE MODES (the result names which one ran): `trusted-dealer` - a separate process that knows every
 * share and key (it can break privacy and integrity if it colludes; but a dealer that gives a WRONG triple is
 * detected by the sacrifice, and a dealer that deals inconsistent MACs is named by the blame round); and
 * `no-dealer` - the parties derive the MAC keys, triples, authenticated inputs and pairwise tags themselves
 * from OT.
 *
 * IDENTIFIABLE ABORT: in BOTH modes every share is pairwise-authenticated (`pa.ts`; dealt by the dealer, or
 * generated by the parties from OT in `offline-net.ts`), so a party that lies about a share, a tag, a MAC share
 * or a residual in the ONLINE phase is named by the honest verifiers with first-hand evidence. What stays
 * unnamed: in no-dealer mode, a wrong OT operand in the offline triple products (the sacrifice detects the bad
 * triple but its tags are consistent with it) - named only for n = 2, where the peer is the only possible
 * culprit; and a verifier's accusation is evidence for the accuser only, never proof for a third party.
 * Network-level misbehaviour (framing, commitments, timeouts) is attributed in both modes.
 *
 * HONEST LIMITS: there is no security proof for this implementation; the echo-broadcast is a hash exchange, not
 * a Byzantine agreement protocol; the trusted dealer is trusted for privacy.
 */

