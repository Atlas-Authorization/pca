/** Shared helper: canonical numbers per party in a dealer `prep` frame. */
function prepLayout(n: number, C: number, keys: number, partners: number, tagged: boolean): { nums: number; triples: number; inputs: number } {
  const aw = awWidth(n, keys, tagged);
  const triples = (n - 1) * C;
  const inputs = n * C;
  const nums = (tagged ? 1 : 0) + keys * paWidth(n, tagged) + triples * sharingsPerTriple(partners) * aw + inputs * aw + C;
  return { nums, triples, inputs };
}

