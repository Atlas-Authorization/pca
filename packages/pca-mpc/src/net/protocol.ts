export interface DealerConfig {
  /** Required `true`: the dealer sees every share and key. */
  insecureTrustedDealer?: boolean;
  n: number;
  Q?: number;
  mesh: Mesh;
  /** Deterministic stream for reproducible tests; omit in real runs (CSPRNG). */
  seed?: bigint;
  /** TEST ONLY: a LYING dealer that authenticates a wrong product c = a*b + delta. */
  fault?: DealerFault;
  /** TEST ONLY: a dealer that deals party 0 a MAC share of input mask number `macFaultAtInput` that does not match its value. */
  macFaultAtInput?: number;
}

/** Hex numbers per `prep` frame (keeps every frame far below the frame cap). */
const PREP_CHUNK = 30_000;

/**
 * The TRUSTED DEALER role: samples the MAC keys, the verification keys, sacrifice-certified authenticated
 * triples and authenticated input masks, and ships each party only its own slice. It never sees any party's
 * input bit (inputs are masked by r and the masked value is broadcast only among parties), but it knows every
 * key and share, so it can break privacy/integrity if it colludes with parties. That is the stated trust
 * assumption of this mode. A dealer that deals a wrong triple is caught by the parties' sacrifice check.
 */
export async function runDealer(cfg: DealerConfig): Promise<void> {
  const { n, mesh } = cfg;
  if (cfg.insecureTrustedDealer !== true) throw new Error('runDealer requires insecureTrustedDealer: true (a dealer sees every share and MAC key; the default offline phase has no dealer)');
  const Q = cfg.Q ?? DEFAULT_Q;
  const rng: FieldRng = cfg.seed !== undefined ? new FieldRng(cfg.seed) : new SecureFieldRng();
  const C = chainCount(Q);
  const ctx = setupMac(n, rng, MAC_KEYS);
  const keys = macKeys(ctx);
  const deltas = Array.from({ length: n }, () => {
    let d = rng.next();
    while (d === 0n) d = rng.next();
    return d;
  });

  /** Deal the pairwise tags/keys for one sharing x_0..x_{n-1}: T_ij = K_ij + Δ_j·x_i. */
  const dealPA = (x: bigint[]): PA[] => {
    const K = x.map((_, i) => x.map((__, j) => (i === j ? 0n : rng.next())));
    return x.map((xi, p) => ({
      x: xi,
      tag: x.map((_, j) => (j === p ? 0n : fadd(K[p]![j]!, fmul(deltas[j]!, xi)))),
      key: x.map((_, j) => (j === p ? 0n : K[j]![p]!)),
    }));
  };
  const dealAW = (sv: AuthSV): AW[] => {
    const comps = [sv.value, sv.mac, ...sv.extraMac].map(dealPA);
    return Array.from({ length: n }, (_, p) => ({ v: comps[0]![p]!, m: comps.slice(1).map((c) => c[p]!) }));
  };

  const perParty: bigint[][] = Array.from({ length: n }, (_, p) => [deltas[p]!]);
  const alphaPA = keys.map((k) => dealPA(k.alphaShares));
  for (let p = 0; p < n; p++) for (const a of alphaPA) perParty[p]!.push(...paFlat(a[p]!, p, n, true));

  const nTriples = (n - 1) * C;
  for (let t = 0; t < nTriples; t++) {
    const tr = genTripleWithPartners(ctx, rng, SACRIFICE_PARTNERS, cfg.fault);
    const sharings = [tr.keep.a, tr.keep.b, tr.keep.c, ...tr.partners.flatMap((q) => [q.a, q.c])];
    for (const sv of sharings) {
      const aws = dealAW(sv);
      for (let p = 0; p < n; p++) perParty[p]!.push(...awFlat(aws[p]!, p, n, true));
    }
  }
  const masksByOwner: bigint[][] = Array.from({ length: n }, () => []);
  for (let q = 0; q < n * C; q++) {
    const owner = Math.floor(q / C);
    const r = rng.next();
    masksByOwner[owner]!.push(r);
    const sv = authShare(r, ctx, rng);
    if (cfg.macFaultAtInput === q) sv.mac[0] = fadd(sv.mac[0]!, 1n);
    const aws = dealAW(sv);
    for (let p = 0; p < n; p++) perParty[p]!.push(...awFlat(aws[p]!, p, n, true));
  }
  for (let p = 0; p < n; p++) perParty[p]!.push(...masksByOwner[p]!);

  for (let p = 0; p < n; p++) {
    const nums = perParty[p]!.map(hx);
    const chunks = Math.max(1, Math.ceil(nums.length / PREP_CHUNK));
    mesh.send(p, 'prep', { total: nums.length, chunks, nums: nums.slice(0, PREP_CHUNK) });
    for (let c = 1; c < chunks; c++) mesh.send(p, `prep.${c}`, nums.slice(c * PREP_CHUNK, (c + 1) * PREP_CHUNK));
  }
  await mesh.finish();
}

