/**
 * A sacrifice / MAC-check abort in the OFFLINE phase together with the parties whose OT transcript is
 * inconsistent. `blamed` lists a party when (i) as an OT sender it offered a pair that does not contain the
 * value the receiver actually obtained, or (ii) the product share it used differs from the one its OT
 * transcripts imply (a wrong operand). Empty when nothing in the disclosed transcript is inconsistent (e.g.
 * the lie was on an unchosen branch). The transcript disclosed is that of the DISCARDED triple only (random
 * triple shares and OT masks, never a MAC-key share, never an input), so naming does not weaken privacy.
 */
export class OfflineCheatingAbort extends MacCheckAbort {
  readonly blamed: readonly number[];
  constructor(message: string, blamed: readonly number[]) {
    super(blamed.length ? `${message}; offline OT transcript names party ${blamed.join(', ')}` : message);
    this.name = 'OfflineCheatingAbort';
    this.blamed = blamed;
  }
}

/** One OT multiplication as the aborted-triple transcript records it (sender's CLAIMED pairs, receiver's outputs). */
interface OtRecord {
  receiver: number;
  sender: number;
  msg0: bigint[];
  msg1: bigint[];
  received: bigint[];
}

/** The product shares a triple-product step claimed per party, against what its OT transcripts imply. */
interface ProductClaim {
  claimed: bigint[];
  implied: bigint[];
}

/**
 * A TEST-ONLY injection modelling a MALICIOUS party in the OFFLINE phase: when the triple PRODUCT
 * multiplication at index `productMul` runs (0-based, counting only the OT multiplications that form a
 * triple's `c = a·b`), `delta` is XOR... added into one party's product share. The resulting triple has
 * `c = a·b + delta` but is still internally MAC-consistent (the authentication runs on the corrupted
 * share) — exactly the "bad OT input" a malicious party can mount, which MACs ALONE cannot catch and
 * the MASCOT SACRIFICE is designed to catch. Models "corrupting an OT message/share in the offline".
 */
export interface OfflineDeviation {
  /** Which triple-product OT multiplication to corrupt (0-based across all products this instance makes). */
  productMul: number;
  /** Field delta added to party 0's product share, making c = a·b + delta (self-consistently MAC'd). */
  delta: bigint;
}

/** Options for the no-dealer offline phase. */
export interface NoDealerOptions {
  /** Run the MASCOT sacrifice on every delivered triple (default true = malicious-secure). */
  sacrifice?: boolean;
  /** Independent sacrifice partners per delivered triple (default `SACRIFICE_PARTNERS` = 2, ≈ 2^-122 soundness). */
  sacrificePartners?: number;
  /** Independent global MAC keys (default `MAC_KEYS` = 2, ≈ 2^-120 MAC soundness). */
  macKeys?: number;
  /** A test-only offline deviation (a malicious party corrupting a product share). */
  deviation?: OfflineDeviation;
  /**
   * Statistical parameter `s` of the OT choice-bit privacy amplification (MASCOT, `enc.ts`): receivers choose with
   * `61 + 3s` uniform bits whose gadget sum is their share, which bounds the leakage of any selective-failure
   * attack by about 2^-s (RT-04). Default 64; values below 40 are refused unless `unsafeStatSec` is set. `0`
   * selects the LEGACY plain binary choice bits, which leak a share bit per abort: UNSAFE, kept only so tests can
   * demonstrate the attack.
   */
  statSec?: number;
  /** TEST ONLY: allow `statSec` below 40 (including the legacy 0). */
  unsafeStatSec?: boolean;
}

/**
 * The no-dealer offline phase for a fixed party count `n`. Holds the distributed MAC key (α_i only),
 * and a reusable set of per-ordered-pair OT-extension channels so the κ base OTs are amortized across
 * every triple and input it produces. Deterministic given its seed (production: a CSPRNG per party).
 *
 * MALICIOUS-secure: the OT extension carries the KOS correlation check (`ot.ts`), and every delivered
 * triple survives the MASCOT sacrifice. `checkInputConsistency` provides the input check.
 */
export class NoDealerOffline {
  readonly n: number;
  /** α_i: party i's locally-sampled share of MAC key 0. Σ α_i = α (never formed by any party). */
  readonly alphaShares: bigint[];
  /** Shares of every MAC key: `keyShares[l][i]` is party i's share of key l (`keyShares[0] === alphaShares`). */
  private readonly keyShares: bigint[][];
  /** The choice-bit encodings of the MAC-key shares (`keyEnc[l][i]` encodes `keyShares[l][i]`). */
  private readonly keyEnc: EncShare[][];
  /** The public gadget vector of the OT choice-bit encoding (`enc.ts`). */
  private readonly gadget: bigint[];
  /** The statistical parameter of the encoding. */
  readonly statSec: number;
  private readonly sacrificePartners: number;
  private readonly rng: FieldRng;
  private readonly seed: bigint;
  /** Whether randomness is a deterministic (test) seed; when false, all randomness is the CSPRNG. */
  private readonly deterministic: boolean;
  /** OT channels keyed "i->j": receiver = party i, sender = party j. Base OTs run on first use. */
  private readonly channels = new Map<string, OtChannel>();
  /** Whether to run the MASCOT sacrifice per delivered triple (malicious-secure when true). */
  private readonly sacrificeOn: boolean;
  /** Test-only offline deviation (a malicious party corrupting a product share). */
  private readonly deviation?: OfflineDeviation;
  /** Count of triple-product OT multiplications performed (for targeting `deviation.productMul`). */
  private productMulCount = 0;
  /** Transcript of the triple being generated (for attribution on abort); null when not recording. */
  private log: OtRecord[] | null = null;
  private claims: ProductClaim[] = [];

  constructor(n: number, seed?: bigint, opts: NoDealerOptions = {}) {
    if (!Number.isInteger(n) || n < 1) throw new Error('NoDealerOffline: n must be a positive integer');
    this.n = n;
    // CSPRNG by DEFAULT (production); a deterministic SplitMix64 stream ONLY when a test seed is given
    // (docs §7.1 item c). `this.seed` is kept for per-pair OT-stream derivation in the deterministic case.
    this.deterministic = seed !== undefined;
    this.seed = seed ?? 0xabcdef12345n;
    this.rng = this.deterministic ? new FieldRng(this.seed) : new SecureFieldRng();
    this.sacrificeOn = opts.sacrifice ?? true;
    this.deviation = opts.deviation;
    // DISTRIBUTED MAC-KEY GENERATION: each party samples its own α_i locally. α is never reconstructed.
    const keys = opts.macKeys ?? MAC_KEYS;
    if (!Number.isInteger(keys) || keys < 1 || keys > 16) throw new Error('NoDealerOffline: macKeys must be an integer in [1, 16]');
    this.statSec = opts.statSec ?? STAT_SEC;
    this.gadget = makeGadget(this.statSec, () => this.rng.next(), opts.unsafeStatSec === true);
    this.keyEnc = Array.from({ length: keys }, () => Array.from({ length: n }, () => sampleEnc(this.gadget, this.rng)));
    this.keyShares = this.keyEnc.map((row) => row.map((e) => e.value));
    this.alphaShares = this.keyShares[0]!;
    this.sacrificePartners = opts.sacrificePartners ?? SACRIFICE_PARTNERS;
    if (!Number.isInteger(this.sacrificePartners) || this.sacrificePartners < 1 || this.sacrificePartners > 8) {
      throw new Error('NoDealerOffline: sacrificePartners must be an integer in [1, 8]');
    }
  }

  /**
   * The SPDZ MAC context the online runner consumes. It carries ONLY `alphaShares` for the protocol;
   * `alpha` is the sum the in-process simulator computes for TEST ASSERTIONS and is never used by any
   * protocol step or held by any party.
   */
  get macContext(): MacContext {
    const keys = this.keyShares.map((shares) => {
      let alpha = 0n;
      for (const ai of shares) alpha = fadd(alpha, ai);
      return { alphaShares: shares.slice(), alpha };
    });
    return { n: this.n, ...keys[0]!, extraKeys: keys.slice(1) };
  }

  private channel(i: number, j: number): OtChannel {
    const key = `${i}->${j}`;
    let ch = this.channels.get(key);
    if (!ch) {
      // CSPRNG by default; a distinct DETERMINISTIC OT stream per ordered pair only under a test seed.
      const otRng: OtRandom = this.deterministic
        ? otRandom(splitMix64(this.seed ^ (BigInt(i + 1) * 0x100000001b3n) ^ (BigInt(j + 1) * 0x1000000000n)))
        : secureOtRandom();
      ch = new OtChannel(otRng);
      this.channels.set(key, ch);
    }
    return ch;
  }

  /**
   * A fresh uniform receiver operand for `party` (uniform bits, and the share they encode). Every share a
   * party multiplies with as OT receiver (triple shares, MAC-key shares) comes from here: the bits are the OT
   * choice bits, so a selective-failure abort tells the sender only about bits of `b`, not about the share.
   */
  private sampleShare(party: number): EncShare {
    void party;
    return sampleEnc(this.gadget, this.rng);
  }

  /**
   * BATCHED OT-based share multiplication. Each request `{x, y}` is a pair of additive sharings (length n) whose product
   * sharing `z` (`Σ z = (Σ x)(Σ y) mod p`) is wanted. All requests are multiplied with ONE OT-extension round per ordered
   * pair (the KOS padding rows and the per-round fixed costs are paid once, not per multiplication). Diagonal terms are
   * local; each cross term `x_i·y_j` is a Gilboa multiplication in which party `i` is the OT receiver with choice bits
   * `bits` and weights `gad` (its operand is `<gad, bits>`) and party `j` offers `(ρ_k, ρ_k + gad_k·y_j)`. No party learns
   * Σx, Σy or Σz.
   *
   * Entries of `x` given as `EncShare` use their own choice bits (privacy-amplified, see `enc.ts`). A plain bigint `x_i`
   * has no uniform encoding, so it is split as `x_i = e + d` with a fresh encoded `e` and `d = x_i − e` (uniform given what
   * an encoded-bit leak reveals), and both halves are multiplied.
   */
  private mulBatch(reqs: ReadonlyArray<{ x: ReadonlyArray<bigint | EncShare>; y: SharedValue }>): SharedValue[] {
    type Part = { bits: readonly number[]; gad: readonly bigint[] };
    const n = this.n;
    for (const r of reqs) if (r.x.length !== n || r.y.length !== n) throw new Error('otShareMultiply: wrong length');
    const pieces = reqs.map((r) =>
      r.x.map((xi): { value: bigint; parts: Part[] } => {
        if (typeof xi !== 'bigint') return { value: xi.value, parts: [{ bits: xi.bits, gad: this.gadget }] };
        const v = mod(xi);
        const e = sampleEnc(this.gadget, this.rng);
        const d = plainShare(fsub(v, e.value));
        return {
          value: v,
          parts: [
            { bits: e.bits, gad: this.gadget },
            { bits: d.bits, gad: PLAIN_GADGET },
          ],
        };
      }),
    );
    const z = reqs.map((r, q) => pieces[q]!.map((p, i) => fmul(p.value, r.y[i]!))); // diagonal x_i·y_i (local)
    for (let i = 0; i < n; i++) {
      for (let j = 0; j < n; j++) {
        if (i === j) continue;
        let rows = 0;
        for (let q = 0; q < reqs.length; q++) for (const part of pieces[q]![i]!.parts) rows += part.bits.length;
        const bits: number[] = new Array(rows);
        const msg0: bigint[] = new Array(rows);
        const msg1: bigint[] = new Array(rows);
        const segs: Array<{ q: number; start: number; len: number; senderSum: bigint }> = [];
        let at = 0;
        for (let q = 0; q < reqs.length; q++) {
          const y = mod(reqs[q]!.y[j]!);
          for (const part of pieces[q]![i]!.parts) {
            const len = part.bits.length;
            let senderSum = 0n; // Σ ρ_k
            for (let k = 0; k < len; k++) {
              const rho = this.rng.next();
              senderSum = fadd(senderSum, rho);
              bits[at + k] = part.bits[k]!;
              msg0[at + k] = rho;
              msg1[at + k] = fadd(rho, fmul(part.gad[k]!, y));
            }
            segs.push({ q, start: at, len, senderSum });
            at += len;
          }
        }
        const { received } = this.channel(i, j).extend(bits, msg0, msg1);
        this.log?.push({ receiver: i, sender: j, msg0, msg1, received });
        for (const sg of segs) {
          let receiverSum = 0n; // Σ (received_k mod p)
          for (let k = 0; k < sg.len; k++) receiverSum = fadd(receiverSum, mod(received[sg.start + k]!));
          // shareI + shareJ = Σ received − Σ ρ = (<gad,bits>·y_j + Σρ) − Σρ = <gad,bits>·y_j.
          z[sg.q]![i] = fadd(z[sg.q]![i]!, receiverSum);
          z[sg.q]![j] = fadd(z[sg.q]![j]!, fneg(sg.senderSum));
        }
      }
    }
    return z;
  }

  /** One OT multiplication (see `mulBatch`): `Σ z = (Σ x)(Σ y)`. */
  otShareMultiply(x: ReadonlyArray<bigint | EncShare>, y: SharedValue): SharedValue {
    return this.mulBatch([{ x, y }])[0]!;
  }

  /** Authenticate a value sharing: MAC shares γ^(l) with Σ γ^(l) = α^(l)·(Σ value) for every key l, via OT (no dealer). */
  private authenticate(valueShares: SharedValue): AuthSV {
    return this.toAuth(valueShares, this.mulBatch(this.keyEnc.map((alphas) => ({ x: alphas, y: valueShares }))));
  }

  private toAuth(value: SharedValue, macs: SharedValue[]): AuthSV {
    return { value, mac: macs[0]!, extraMac: macs.slice(1) };
  }

  /** Test hook (deviation) + attribution record for a triple product sharing `implied`; returns the claimed sharing. */
  private claimProduct(implied: SharedValue): SharedValue {
    const z = implied.slice();
    const idx = this.productMulCount++;
    const dev = this.deviation;
    if (dev && dev.productMul === idx) z[0] = fadd(z[0]!, dev.delta);
    this.claims.push({ claimed: z, implied });
    return z;
  }

  /**
   * One raw authenticated triple `(a, b, c = a·b)` together with `partners` sacrifice triples `(â_r, b, ĉ_r)` sharing `b`,
   * from OT with NO dealer, in TWO batched OT layers: layer 1 = all products and the MACs of every value known before them,
   * layer 2 = the MACs of the products. Each value's MAC is `α^(l)·value` for every key `l`.
   */
  private rawTripleWithPartners(partners: number): { keep: AuthTriple; partners: AuthTriple[] } {
    const n = this.n;
    const K = this.keyEnc.length;
    const aEnc = Array.from({ length: n }, (_, i) => this.sampleShare(i));
    const bShares = Array.from({ length: n }, () => this.rng.next());
    const ahEnc = Array.from({ length: partners }, () => Array.from({ length: n }, (_, i) => this.sampleShare(i)));
    const aVal = aEnc.map((e) => e.value);
    const ahVal = ahEnc.map((row) => row.map((e) => e.value));
    const reqs: Array<{ x: ReadonlyArray<bigint | EncShare>; y: SharedValue }> = [{ x: aEnc, y: bShares }];
    for (let r = 0; r < partners; r++) reqs.push({ x: ahEnc[r]!, y: bShares });
    const macStart = reqs.length;
    for (let l = 0; l < K; l++) {
      reqs.push({ x: this.keyEnc[l]!, y: aVal });
      reqs.push({ x: this.keyEnc[l]!, y: bShares });
      for (let r = 0; r < partners; r++) reqs.push({ x: this.keyEnc[l]!, y: ahVal[r]! });
    }
    const z1 = this.mulBatch(reqs);
    const cShares = this.claimProduct(z1[0]!);
    const chShares = Array.from({ length: partners }, (_, r) => this.claimProduct(z1[1 + r]!));
    const per = 2 + partners;
    const macOf = (off: number): SharedValue[] => Array.from({ length: K }, (_, l) => z1[macStart + l * per + off]!);
    const reqs2: Array<{ x: ReadonlyArray<bigint | EncShare>; y: SharedValue }> = [];
    for (let l = 0; l < K; l++) {
      reqs2.push({ x: this.keyEnc[l]!, y: cShares });
      for (let r = 0; r < partners; r++) reqs2.push({ x: this.keyEnc[l]!, y: chShares[r]! });
    }
    const z2 = this.mulBatch(reqs2);
    const per2 = 1 + partners;
    const macOf2 = (off: number): SharedValue[] => Array.from({ length: K }, (_, l) => z2[l * per2 + off]!);
    const b = this.toAuth(bShares, macOf(1));
    const keep: AuthTriple = { a: this.toAuth(aVal, macOf(0)), b, c: this.toAuth(cShares, macOf2(0)) };
    const parts: AuthTriple[] = Array.from({ length: partners }, (_, r) => ({
      a: this.toAuth(ahVal[r]!, macOf(2 + r)),
      b,
      c: this.toAuth(chShares[r]!, macOf2(1 + r)),
    }));
    return { keep, partners: parts };
  }

  /** Name the parties whose transcript of the discarded triple is inconsistent (see `OfflineCheatingAbort`). */
  private attribute(abort: MacCheckAbort): MacCheckAbort {
    const blamed = new Set<number>();
    for (const r of this.log ?? []) {
      for (let k = 0; k < r.received.length; k++) {
        const got = mod(r.received[k]!);
        if (got !== r.msg0[k] && got !== r.msg1[k]) {
          blamed.add(r.sender); // the receiver holds a value the sender never offered
          break;
        }
      }
    }
    for (const c of this.claims) {
      c.claimed.forEach((v, i) => {
        if (v !== c.implied[i]) blamed.add(i); // a product share that does not follow from its OT transcripts
      });
    }
    return new OfflineCheatingAbort(abort.message, [...blamed].sort((p, q) => p - q));
  }

  /**
   * Generate ONE authenticated Beaver triple with NO dealer, MALICIOUS-secure. Each party samples its
   * own a_i, b_i; the product sharing c (Σc = a·b) comes from OT; every component is MAC'd via OT
   * against the α shares. When the sacrifice is on (default), a SECOND triple sharing `b` is generated
   * and sacrificed to certify `c = a·b` under the MACs, so a malformed triple ABORTS rather than being
   * emitted. No party learns a, b, c, or α. The OT choice bits are privacy-amplified (`enc.ts`), so whether
   * a run aborts is statistically independent of any share an honest party holds (RT-04). An abort throws
   * `OfflineCheatingAbort`, which names the party whose OT transcript is inconsistent where one is.
   */
  genAuthTriple(): AuthTriple {
    if (!this.sacrificeOn) return this.rawTripleWithPartners(0).keep;
    this.log = [];
    this.claims = [];
    try {
      const { keep, partners } = this.rawTripleWithPartners(this.sacrificePartners);
      // The MASCOT sacrifice (spdz.ts `sacrificeVerify`): throws MacCheckAbort and emits no triple on a bad c.
      return sacrificeVerify([{ keep, partners }], this.macContext, this.rng)[0]!;
    } catch (e) {
      if (e instanceof MacCheckAbort) throw this.attribute(e);
      throw e;
    } finally {
      this.log = null;
      this.claims = [];
    }
  }

  /** Generate `count` authenticated triples (channels/base-OTs amortized across all of them). */
  genAuthTriples(count: number): AuthTriple[] {
    const out: AuthTriple[] = [];
    for (let k = 0; k < count; k++) out.push(this.genAuthTriple());
    return out;
  }

  /**
   * Authenticated input sharing of `value`, owned by party `owner`, with NO dealer. The owner splits
   * its own value into additive shares (local); the MAC `α·value` is computed via OT against the α
   * shares. A malicious owner can of course choose any value (inputs are unconstrained in SPDZ), but it
   * cannot make the sharing inconsistent with its MAC — the online MAC-check binds it.
   */
  authInput(value: bigint, owner: number): AuthSV {
    if (owner < 0 || owner >= this.n) throw new Error('authInput: owner out of range');
    const valueShares = share(mod(value), this.n, this.rng);
    return this.authenticate(valueShares);
  }

  /**
   * The MASCOT **input-consistency check**: verify that a batch of authenticated inputs each satisfy
   * `Σγ = α·(Σvalue)` — i.e. their MACs match their values — WITHOUT revealing any value, and ABORT if
   * not. A malicious party that produced an input whose MAC does not match its value (e.g. by feeding a
   * bad OT input to the authentication) is caught here rather than only downstream.
   *
   * Method: draw public random coefficients `e_k`, generate ONE fresh OT-authenticated random mask
   * `⟦r⟧`, form `⟦w⟧ = Σ_k e_k·⟦x_k⟧ + ⟦r⟧`, partial-open `w` (masked by the uniform `r`, so no input
   * leaks), and run the commit-then-open MAC-check on that opening. If some input's MAC is off by `δ`,
   * the opened `w` carries MAC residual `Σ e_k·δ_k ≠ 0` w.h.p. over the random `e_k`, and the MAC-check
   * aborts. No-op for an empty batch.
   */
  checkInputConsistency(inputs: ReadonlyArray<AuthSV>): void {
    if (inputs.length === 0) return;
    for (const inp of inputs) {
      if (inp.value.length !== this.n || inp.mac.length !== this.n) {
        throw new Error('checkInputConsistency: input party count mismatch');
      }
    }
    const ctx = this.macContext;
    const engine = new SpdzEngine(ctx, []);
    // Fresh OT-authenticated random mask ⟦r⟧ (hides w so no input value is revealed).
    const rShares = Array.from({ length: this.n }, () => this.rng.next());
    let w: AuthSV = this.authenticate(rShares);
    for (const inp of inputs) {
      let e = this.rng.next(); // public random coefficient
      if (e === 0n) e = 1n; // weight every input (0 would skip one); bias is negligible (prob 1/p)
      w = addAuth(w, scaleAuth(inp, e));
    }
    engine.open(w, 'input-check:w');
    engine.macCheck(this.rng); // throws MacCheckAbort if any input's MAC is inconsistent with its value
  }
}

/**
 * The offline material a malicious-secure runner consumes. A `NoDealerOffline` IS one of these
 * (duck-typed by `macContext`/`genAuthTriple`/`authInput`), so the runner can take either this or the
 * trusted-dealer functions behind the same tiny interface.
 */
export interface OfflineProvider {
  readonly n: number;
  readonly macContext: MacContext;
  genAuthTriple(): AuthTriple;
  authInput(value: bigint, owner: number): AuthSV;
}

/** Convenience: a fresh no-dealer offline phase for `n` parties (malicious-secure by default). */
export function makeNoDealerOffline(
  n: number,
  seed?: bigint,
  opts?: NoDealerOptions,
): NoDealerOffline {
  return new NoDealerOffline(n, seed, opts);
}
