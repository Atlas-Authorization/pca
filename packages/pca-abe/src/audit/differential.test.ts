import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { describe, expect, it } from 'vitest';
import { bls12_381 } from '@noble/curves/bls12-381';
import {
  G1_BASE,
  G2_BASE,
  R,
  g1FromBytes,
  g1Mul,
  g1ToBytes,
  g2FromBytes,
  g2Mul,
  g2ToBytes,
  gtEql,
  gtPow,
  gtToBytes,
  hashAttrToG1,
  frAdd,
  frInv,
  frMul,
  pairing,
} from '../bls';
import { type DecryptionKey, type MasterPublicKey, decrypt, encryptForPolicy } from '../index';
import { recoverSecret } from '../sss';

/**
 * Differential tests against an INDEPENDENT implementation. The fixture was generated by py_ecc 8.0.0
 * (pure-Python, different code base, different author from @noble/curves) via test-oracle/gen_vectors.py.
 * py_ecc itself asserted the BSW07 leaf equation  e(D_j, C) = e(g1,g2)^(r*q) * e(C', D'_j)  and the root equation
 * e(D, C_0) = e(g1,g2)^((alpha+r)*s)  for every case before emitting it.
 */

interface Case {
  attr: string;
  alpha: string; beta: string; r: string; rj: string; q: string; s: string;
  Q: string; h: string; f: string; aG1: string; D: string; Dj: string; Dpj: string; C0: string; C: string; Cp: string;
}
interface ShamirCase { t: number; n: number; secret: string; shares: [number, string][] }
const V = JSON.parse(readFileSync(join(__dirname, 'vectors', 'abe-pyecc.json'), 'utf8')) as { cases: Case[]; shamir: ShamirCase[] };
const big = (h: string) => BigInt('0x' + h);
const hex = (u: Uint8Array) => Buffer.from(u).toString('hex');
const g1 = (h: string) => {
  const p = g1FromBytes(Buffer.from(h, 'hex'));
  if (p === null) throw new Error('fixture G1 point rejected');
  return p;
};
const g2 = (h: string) => {
  const p = g2FromBytes(Buffer.from(h, 'hex'));
  if (p === null) throw new Error('fixture G2 point rejected');
  return p;
};
const Fp12 = bls12_381.fields.Fp12;
const gtMul = (a: Parameters<typeof Fp12.mul>[0], b: Parameters<typeof Fp12.mul>[1]) => Fp12.mul(a, b);
const eGG = pairing(G1_BASE, G2_BASE);

describe('BLS12-381 BSW07 key and ciphertext components agree with py_ecc', () => {
  it('has the expected number of reference cases', () => {
    expect(V.cases.length).toBeGreaterThanOrEqual(10);
  });

  for (const c of V.cases) {
    const label = JSON.stringify(c.attr.length > 20 ? c.attr.slice(0, 10) + '...' : c.attr);
    const [alpha, beta, r, rj, q, s] = [c.alpha, c.beta, c.r, c.rj, c.q, c.s].map(big) as [bigint, bigint, bigint, bigint, bigint, bigint];

    it(`hash-to-G1 (RFC 9380 SSWU_RO with the scheme DST) matches for ${label}`, () => {
      expect(hex(g1ToBytes(hashAttrToG1(c.attr)))).toBe(c.Q);
    });
    it(`public key elements h = beta*g2, f = beta^-1*g1 match for ${label}`, () => {
      expect(hex(g2ToBytes(g2Mul(G2_BASE, beta)))).toBe(c.h);
      expect(hex(g1ToBytes(g1Mul(G1_BASE, frInv(beta))))).toBe(c.f);
    });
    it(`key components D, D_j, D'_j match for ${label}`, () => {
      expect(hex(g1ToBytes(g1Mul(G1_BASE, frMul(frAdd(alpha, r), frInv(beta)))))).toBe(c.D);
      const dj = g1Mul(G1_BASE, r).add(g1Mul(hashAttrToG1(c.attr), rj));
      expect(hex(g1ToBytes(dj))).toBe(c.Dj);
      expect(hex(g2ToBytes(g2Mul(G2_BASE, rj)))).toBe(c.Dpj);
    });
    it(`ciphertext components C_0, C_x, C'_x match for ${label}`, () => {
      expect(hex(g2ToBytes(g2Mul(g2(c.h), s)))).toBe(c.C0);
      expect(hex(g2ToBytes(g2Mul(G2_BASE, q)))).toBe(c.C);
      expect(hex(g1ToBytes(g1Mul(hashAttrToG1(c.attr), q)))).toBe(c.Cp);
    });
    it(`pairing equations hold in noble on the py_ecc points for ${label}`, () => {
      // leaf: e(D_j, C) = e(g1,g2)^(r*q) * e(C', D'_j)
      const leafL = pairing(g1(c.Dj), g2(c.C));
      const leafR = gtMul(gtPow(eGG, frMul(r, q)), pairing(g1(c.Cp), g2(c.Dpj)));
      expect(hex(gtToBytes(leafL))).toBe(hex(gtToBytes(leafR)));
      // root: e(D, C_0) = Y^s * e(g1,g2)^(r*s) with Y = e(alpha*g1, g2) computed from the REFERENCE's alpha*g1
      const y = pairing(g1(c.aG1), G2_BASE);
      expect(gtEql(gtPow(eGG, alpha), y)).toBe(true);
      const rootL = pairing(g1(c.D), g2(c.C0));
      const rootR = gtMul(gtPow(y, s), gtPow(eGG, frMul(r, s)));
      expect(hex(gtToBytes(rootL))).toBe(hex(gtToBytes(rootR)));
      // key/public-key consistency: e(f, h) = e(g1,g2)
      expect(gtEql(pairing(g1(c.f), g2(c.h)), eGG)).toBe(true);
    });
    it(`end to end: a key built ONLY from py_ecc components decrypts a library ciphertext for ${label}`, () => {
      const mpk: MasterPublicKey = {
        v: 1,
        curve: 'bls12-381',
        h: Buffer.from(c.h, 'hex').toString('base64url'),
        f: Buffer.from(c.f, 'hex').toString('base64url'),
        egga: Buffer.from(gtToBytes(pairing(g1(c.aG1), G2_BASE))).toString('base64url'),
      };
      const key: DecryptionKey = {
        v: 1,
        curve: 'bls12-381',
        d: Buffer.from(c.D, 'hex').toString('base64url'),
        attrs: { [c.attr]: { dj: Buffer.from(c.Dj, 'hex').toString('base64url'), dpj: Buffer.from(c.Dpj, 'hex').toString('base64url') } },
      };
      const pt = new TextEncoder().encode('interop');
      const { ciphertext } = encryptForPolicy(mpk, { attr: c.attr }, pt);
      expect(decrypt(key, ciphertext)).toEqual(pt);
    });
  }
});

describe('Unicode normalisation', () => {
  it('the two non-equal Unicode normalisations of the same text hash to different points in BOTH implementations', () => {
    const forms = V.cases.filter((c) => c.attr.normalize('NFC') === 'caf\u00e9');
    expect(forms.length).toBe(2);
    expect(forms[0]?.attr).not.toBe(forms[1]?.attr);
    expect(forms[0]?.Q).not.toBe(forms[1]?.Q);
    for (const f of forms) expect(hex(g1ToBytes(hashAttrToG1(f.attr)))).toBe(f.Q);
  });
});

describe('Shamir recovery agrees with an independent Lagrange implementation (Python integers)', () => {
  const mask = (n: number, k: number): number[][] => {
    // all k-subsets of 0..n-1
    const out: number[][] = [];
    const rec = (start: number, cur: number[]) => {
      if (cur.length === k) { out.push(cur.slice()); return; }
      for (let i = start; i < n; i++) { cur.push(i); rec(i + 1, cur); cur.pop(); }
    };
    rec(0, []);
    return out;
  };
  for (const c of V.shamir) {
    it(`t=${c.t} n=${c.n}: every size-t subset recovers the secret; every smaller subset does not`, () => {
      const shares = c.shares.map(([x, y]) => ({ x: BigInt(x), y: big(y) }));
      for (const sub of mask(c.n, c.t)) expect(recoverSecret(sub.map((i) => shares[i]!))).toBe(big(c.secret));
      if (c.t > 1) {
        for (const sub of mask(c.n, c.t - 1)) expect(recoverSecret(sub.map((i) => shares[i]!))).not.toBe(big(c.secret));
      }
      expect(c.secret.length).toBe(64);
      expect(big(c.secret) < R).toBe(true);
    });
  }
});
