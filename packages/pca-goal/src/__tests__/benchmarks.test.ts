import * as fs from 'node:fs';
import * as path from 'node:path';
import { readFileSync, mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { describe, expect, it } from 'vitest';
import { DOMAINS, HOSTILE_N, MAIN_N, fixturesFor, hostileCases, mainCases } from '../../benchmarks/data';
import { DOMAIN_ALPHA, HOSTILE_KINDS, compileWideningCount, requestOf, runDomain, truthGoal, truthOnt } from '../bench';
import { cpUpper95, renderReportMarkdown, type DomainReport } from '../crc';
import { allowsWitness } from '../disambiguate';
import { boundaryExamples, buildSpace, cells, decideCase } from '../examples';
import { ruleInterpreter, type Recordings } from '../interpret';
import type { Goal, Ontology } from '../ir';
import { ALL_ONTOLOGIES } from '../ontologies';
import { goalAnchors, ontologyForGoal } from '../ontology';
import { compileGoal, decidePolicy, typecheck } from '../compiler';

// The proved compiler is generated by formal/dafny/build-ext.sh Goal; compile-widening against it runs where it exists (CI requires it).
const haveGen = fs.existsSync(path.resolve(__dirname, '../../../pca-verified-core/generated/pca_goal.js'));
if (process.env.PCA_GOAL_REQUIRE === '1' && !haveGen) throw new Error('generated/pca_goal.js is missing but PCA_GOAL_REQUIRE=1');

const rec = (d: string): Recordings => JSON.parse(readFileSync(join(process.cwd(), 'benchmarks/recorded', `${d}.json`), 'utf8')) as Recordings;
const reports: DomainReport[] = [];

describe('recorded model outputs are reproducible', () => {
  for (const d of DOMAINS) it(`${d}: committed recordings equal a fresh deterministic recording`, () => expect(rec(d)).toEqual(Object.fromEntries(Object.entries(fixturesFor(d)).sort(([a], [b]) => (a < b ? -1 : 1)))));
});

describe('labelled benchmarks per domain (offline, recorded outputs)', () => {
  for (const d of DOMAINS) {
    it(`${d}: widening-rate gate at the calibrated level, 95% upper bound <= alpha`, async () => {
      const cases = mainCases(d);
      expect(cases.length).toBe(MAIN_N);
      const r = await runDomain(d, cases, rec(d));
      reports.push(r.report);
      expect(r.report.compileWidening.k).toBe(0);
      expect(r.report.compileWidening.n).toBeGreaterThan(100);
      expect(r.report.test.widening.cpUpper95).toBeLessThanOrEqual(DOMAIN_ALPHA[d]!);
      expect(r.report.gatePassed).toBe(true);
      // the meet never widens more than any single reading (the proved property, measured)
      const [single, meetLevel] = r.report.perLevel;
      expect(meetLevel!.widening.k).toBeLessThanOrEqual(single!.widening.k);
      // availability cost is real and reported
      expect(r.report.test.escalationRate).toBeGreaterThanOrEqual(0);
    }, 120_000);
  }
  it('writes the report', () => {
    const dir = process.env.PCA_GOAL_REPORT_DIR;
    const md = renderReportMarkdown(reports, { source: 'fixture', modelSet: 'rule + two simulated model families (recorded)' });
    expect(md).toContain('Guarantee and assumptions');
    if (dir) { mkdirSync(dir, { recursive: true }); writeFileSync(join(dir, 'intent-fidelity-fixture.md'), md); writeFileSync(join(dir, 'intent-fidelity-fixture.json'), JSON.stringify(reports, null, 1)); }
  });
});

describe('hostile corpus: widening-rate gates', () => {
  for (const d of DOMAINS) {
    it(`${d}: every case is hostile; meet-level widening upper bound <= alpha; rule reader never widens`, async () => {
      const cases = hostileCases(d);
      expect(cases.length).toBe(HOSTILE_N);
      expect(new Set(cases.map((c) => c.hostile)).size).toBe(HOSTILE_KINDS.length);
      const r = await runDomain(d, cases, rec(d));
      const meetLevel = r.report.perLevel[1]!;
      expect(meetLevel.widening.cpUpper95).toBeLessThanOrEqual(DOMAIN_ALPHA[d]!);
      expect(r.report.perLevel[3]!.widening.k).toBe(0);
      expect(r.report.compileWidening.k).toBe(0);
      // the deterministic reader is not fooled by injected limits, homoglyphs, or planted sources
      const ont = ALL_ONTOLOGIES[d]!;
      let ruleWiden = 0;
      for (const c of cases) {
        const g = (await ruleInterpreter().interpret(requestOf(c))).goal;
        const truth = truthGoal(c), tont = truthOnt(c, truth);
        const probes = boundaryExamples(truth, { ont: tont, verbs: ont.verbs.map((v) => v.id) }).examples;
        if (g.holes.length === 0 && probes.some((e) => e.decision !== 'allow' && allowsWitness(g, tont, { act: e.act, prior: e.hist.adms.map((a) => a.act), rels: e.rels }))) ruleWiden++;
      }
      expect(cpUpper95(ruleWiden, cases.length)).toBeLessThanOrEqual(DOMAIN_ALPHA[d]!);
    }, 120_000);
  }
});

const itemsOf = (): { goal: Goal; ont: Ontology }[] => {
  const out: { goal: Goal; ont: Ontology }[] = [];
  for (const o of Object.values(ALL_ONTOLOGIES)) for (const t of o.templates) for (let i = 0; i < 4; i++) {
    const goal = truthGoal({ id: 'x', domain: o.domain, template: t.id, slots: t.example, text: '', sources: [], flags: [] });
    out.push({ goal, ont: ontologyForGoal(o, goal, goalAnchors(goal)) });
  }
  return out;
};

describe('compile-widening is zero on generated goals (G-T1 style corpus)', () => {
  it('the self-check can fail: a decision function that always allows is caught', () => {
    const items = itemsOf();
    const w = compileWideningCount(items);
    expect(w.k).toBe(0); expect(w.n).toBeGreaterThan(500);
    expect(compileWideningCount(items.slice(0, 3), () => 'allow').k).toBeGreaterThan(0);
  });
  (haveGen ? it : it.skip)('no cell of any template instantiation is allowed by the proved compiled policy but denied by the reference', () => {
    const items = itemsOf();
    for (const { goal, ont } of items.slice(0, 40)) expect(typecheck(goal, ont), goal.grants.map((g) => g.gid).join()).toEqual([]);
    const w = compileWideningCount(items, (g, ont, e) => { const r = decidePolicy(g, { ...ont, rels: e.rels }, e.act, e.hist); return r.ok ? r.decision : 'deny'; });
    expect(w.k).toBe(0); expect(w.n).toBeGreaterThan(500);
    void compileGoal;
  });
  it('every cell the reference allows is inside the declared grants (no allow outside any grant)', () => {
    for (const { goal: g, ont } of itemsOf()) {
      for (const c of cells(buildSpace([g], ont.verbs.map((v) => v.verb))).cases) {
        const v = decideCase(g, ont, c);
        if (v.decision === 'allow') expect(g.grants.some((gr) => gr.gid === v.witness && gr.verb === c.act.verb)).toBe(true);
      }
    }
  });
});
