describe('disambiguation (F1)', () => {
  const g1 = refundGoal();
  const gs = [150, 300, 450, 600, 750, 900, 1200, 1800].map((x) => mk('refund_customer_charges', { customer: 'cus_1', max_per: { ccy: 'USD', minor: x }, max_total: { ccy: 'USD', minor: 9000 }, max_count: { n: 5 } }));
  const readings: Reading[] = gs.map((goal, i) => ({ id: `r${i}`, family: `f${i}`, deterministic: i === 0, goal, notes: [] }));
  const ont = ontOf(g1);
  it('isolates the principal reading within the halving bound', async () => {
    for (const truthIdx of [0, 3, 7]) {
      const truth = gs[truthIdx]!;
      const res = await disambiguate(readings, (q) => (allowsWitness(truth, ont, q) ? 'allow' : 'deny'), { ont });
      expect(res.status).toBe('resolved');
      expect(res.remaining).toEqual([`r${truthIdx}`]);
      expect(res.asked.length).toBeLessThanOrEqual(Math.ceil(Math.log2(readings.length)) + 1);
    }
  });
  it('questions are ranked and finite; no question when readings agree', () => {
    expect(questions([readings[0]!, { ...readings[1]!, goal: gs[0]! }], { ont }).length).toBe(0);
    const qs = questions(readings.slice(0, 2), { ont });
    expect(qs.length).toBeGreaterThan(0); expect(qs[0]!.score).toBeGreaterThanOrEqual(qs[qs.length - 1]!.score);
  });
  it('an exhausted budget keeps a hole (never a guess)', async () => {
    const bud = await disambiguate(readings, () => 'allow', { ont, budget: 0 });
    expect(bud.status).toBe('budget_exhausted'); expect(bud.goal.holes.length).toBeGreaterThan(0);
    expect((await disambiguate(readings, () => 'deny', { ont, budget: 1 })).status).toBe('budget_exhausted');
  });
});

