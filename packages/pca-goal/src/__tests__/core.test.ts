const D = (g: Goal, c: Case, prior: Case[] = []) => {
  const ont = ontOf(g), rels = facts(c, ...prior);
  return decideCase(g, ont, { act: c.act, hist: replay(g, ont, prior.map((p) => p.act), rels), rels }).decision;
};
