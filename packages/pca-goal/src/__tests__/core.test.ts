/** union of the relation facts of several cases (history actions are decided under the same world) */
const facts = (...cs: Case[]): RelDecl[] => {
  const m = new Map<string, RelDecl>();
  for (const c of cs) for (const r of c.rels) { const k = r.rel + '\0' + r.anchor; const p = m.get(k); m.set(k, { ...r, members: [...new Set([...(p?.members ?? []), ...r.members])] }); }
  return [...m.values()];
};
