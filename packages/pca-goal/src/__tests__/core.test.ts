    const hostile = JSON.parse(JSON.stringify(faithful)) as Goal;
    hostile.grants = [{ gid: 'x', verb: 'refund', res: { k: 'any', reason: 'inj' }, cond: { k: 'true' } }]; hostile.bounds = []; hostile.prohibits = [];
