describe('precedents (F7) on the one escalation wire', () => {
  const g = refundGoal();
  const ont = ontOf(g);
  const sp = buildSpace([g]);
  const k = key(); const other = key();
  const grant = { id: 'grant-1', scope: 'refunds' } as unknown as Capability;
  const policyDigest = escalationPolicyDigest(grant);
  const nonce = () => b64u(crypto.getRandomValues(new Uint8Array(16)));
  const pcactnOf = (c: Case, counter = 7): PCActn => ({ action: { verb: c.act.verb, resource: c.act.res, params_digest: paramsDigest(c.act.params), reversibility_class: 'irreversible' }, counter, aud: 'rs', iat: 1, exp: 5000 } as unknown as PCActn);
  const answered = (c: Case) => ({ pcactn: pcactnOf(c), params: c.act.params, rels: c.rels, lastCounter: 6 as number | undefined });
  const ask = (c: Case, o: { signer?: { sk: Uint8Array; pin: string }; decision?: 'allow' | 'deny'; expires?: number; gr?: Capability } = {}) => {
    const req = buildEscalationRequest({ aud: 'rs', grant: o.gr ?? grant, pcactn: pcactnOf(c), lastCounter: 6, reasons: ['unit'], now: 1 });
    const s = o.signer ?? k;
    return signEscalationAnswer(answerBodyFor(req, { principal: s.pin, decision: o.decision ?? 'allow', iat: 1, expires_at: o.expires ?? 1000, nonce: nonce() }), s.sk);
  };
  const escAct = refund('ch_1', 100, 'cus_1', 'EUR');
  const auth = (log: PrecedentLog, c: Case, now: number, pd = policyDigest) => authorizeWithPrecedents(g, ont, pd, log, { act: c.act, rels: c.rels }, now).decision;
  it('widens only with a signature bound to policy, cell and ceiling', () => {
    expect(D(g, escAct)).toBe('escalate');
    const log = new PrecedentLog([k.pin]);
    expect(auth(log, escAct, 10)).toBe('escalate');
    expect(log.append(ask(escAct), answered(escAct), grant, sp, 10).ok).toBe(true);
    expect(auth(log, escAct, 10)).toBe('allow');
    expect(auth(log, escAct, 10, 'other-policy')).toBe('escalate'); // no replay on another policy
    expect(auth(log, refund('ch_1', 101, 'cus_1', 'EUR'), 10)).toBe('escalate'); // beyond the signed ceiling
    expect(auth(log, escAct, 2000)).toBe('escalate'); // expired
    expect(auth(log, refund('ch_1', 100, 'cus_1', 'GBP'), 10)).toBe('escalate'); // a EUR answer never covers GBP
  });
  it('forged, wrong-signer and mismatched answers are refused', () => {
    const log = new PrecedentLog([k.pin]);
    expect(log.append(ask(escAct, { signer: other }), answered(escAct), grant, sp, 10).ok).toBe(false); // unpinned signer
    const grant2 = { id: 'grant-2' } as unknown as Capability;
    expect(log.append(ask(escAct, { gr: grant2 }), answered(escAct), grant, sp, 10).ok).toBe(false); // bound to another policy
    expect(log.append(ask(escAct, { expires: 5 }), answered(escAct), grant, sp, 10).ok).toBe(false); // expired
    expect(log.append(ask(escAct), answered(refund('ch_1', 100, 'cus_1', 'GBP')), grant, sp, 10).ok).toBe(false); // another action
    const lied = { ...answered(escAct), params: refund('ch_1', 1, 'cus_1', 'EUR').act.params };
    expect(log.append(ask(escAct), lied, grant, sp, 10).ok).toBe(false); // params differ from the signed params_digest
    expect(log.append(ask(escAct), { ...answered(escAct), lastCounter: 99 }, grant, sp, 10).ok).toBe(false); // another history state
  });
  it('deny is never widened; flipping needs a signed revocation; tamper locks', () => {
    const log = new PrecedentLog([k.pin]);
    const denied: Case = { act: mkAct('transfer', 'acct_1'), rels: [] };
    log.append(ask(denied), answered(denied), grant, sp, 10);
    expect(auth(log, denied, 10)).toBe('deny'); // P3
    const e1 = log.append(ask(escAct), answered(escAct), grant, sp, 10);
    expect(log.append(ask(escAct, { decision: 'deny' }), answered(escAct), grant, sp, 11).ok).toBe(false); // conflicting flip
    if (!e1.ok) throw new Error('x');
    const body = { policy_digest: policyDigest, cell: e1.entry.cell!, target_entry: e1.entry.digest, ts: 12 };
    expect(log.revoke(signRevocation(body, other.sk)).ok).toBe(false);
    expect(log.revoke(signRevocation(body, k.sk)).ok).toBe(true);
    expect(auth(log, escAct, 13)).toBe('escalate');
    expect(log.verifyChain(sp)).toBe(true);
    (log.entries[0] as any).seq = 5;
    expect(log.verifyChain(sp)).toBe(false);
    expect(auth(log, escAct, 13)).toBe('escalate');
  });
});

describe('drift monitor (F8) is tighten-only', () => {
  const g = refundGoal();
  it('applyDrift is pointwise <= (property)', () => {
    const ord = { deny: 0, escalate: 1, allow: 2 } as const;
    for (const d of ['deny', 'escalate', 'allow'] as const) for (const a of [true, false]) for (const l of [true, false])
      expect(ord[applyDrift(d, { anomalous: a, strikes: 0, lockdown: l, reasons: [] })]).toBeLessThanOrEqual(ord[d]);
  });
  it('off-profile, rate, magnitude and novelty raise friction; strikes never decrease', () => {
    const m = new DriftMonitor(g, { maxPerWindow: 3, lockdown: 3, warmup: 2 });
    expect(m.observe(refund('ch_1', 100).act, 0).anomalous).toBe(false);
    expect(m.observe(mkAct('transfer', 'acct_1'), 1).anomalous).toBe(true);
    let last = m.state().strikes;
    for (let i = 0; i < 6; i++) { m.observe(refund('ch_x', 100).act, 2 + i); expect(m.state().strikes).toBeGreaterThanOrEqual(last); last = m.state().strikes; }
    expect(m.observe(refund('ch_1', 100).act, 20).lockdown).toBe(true);
  });
  it('magnitude spike and sealed state', () => {
    const key = Buffer.from('k'.repeat(32));
    const m = new DriftMonitor(g, { warmup: 3 });
    for (let i = 0; i < 4; i++) m.observe(refund('ch_1', 100).act, i * 100_000);
    expect(m.observe(refund('ch_1', 1900).act, 500_000).anomalous).toBe(true);
    const sealed = m.seal(key);
    expect(DriftMonitor.restore(g, sealed, key).state().strikes).toBe(m.state().strikes);
    const forged = { state: { ...sealed.state, strikes: 0 }, mac: sealed.mac };
    expect(DriftMonitor.restore(g, forged, key).state().strikes).toBeGreaterThan(0); // tamper => lockdown, never relax
  });
});

