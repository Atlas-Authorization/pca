import { b64u, decodePcaNeed, encodePcaNeed, pcaNeedDigest, publicKeyOf, type PcaNeed } from '@atlasauth/pca';
import { checkChainExtension, checkPushNotification, pcaPushToken, resumeGate } from '../a2a-auth';
import { checkReceiptChain, mayTriggerNext, receiptDigest, signTaskReceipt, type TaskReceipt } from '../a2a-receipt';

/**
 * Shared vectors for the A2A binding (packages/pca/conformance/a2a-vectors.json): typed needs, per-hop chain extension, the pure
 * gate of AUTH_REQUIRED resumption, push-token binding and signed task-update receipts. Expectations are written by hand; only
 * digests, tokens and signatures are computed. The builder cross-checks them against the reference and throws on drift.
 * Generated by scripts/gen-a2a-vectors.ts.
 */
const SECRET = new Uint8Array(32).fill(31);
const OTHER = new Uint8Array(32).fill(32);
export const SIGNER = b64u(publicKeyOf(SECRET));
const NOW = 1_800_000_000_000;
const IDS = ['capA', 'capB'];
const SALT = 'a-secret-salt-16+chars';
const enc = (o: unknown) => b64u(new TextEncoder().encode(JSON.stringify(o)));

export function buildA2aVectors() {
  const need: PcaNeed = { v: 1, kind: 'scope', verb: 'purchase', resource: 'cart/42', scopes: ['cart:pay'], limits: { 'money.usd': 40 } };
  const esc: PcaNeed = { v: 1, kind: 'escalate', verb: 'v', resource: 'r', tier: 3, discharges: [{ issuer: 'https://issuer.example', claim: 'kyc' }] };
  const NEED = encodePcaNeed(need);
  const needCases = [
    { name: 'scope-need', input: NEED, expect: { ok: true, digest: pcaNeedDigest(need) } },
    { name: 'escalate-need', input: encodePcaNeed(esc), expect: { ok: true, digest: pcaNeedDigest(esc) } },
    { name: 'padded', input: `${NEED}=`, expect: { ok: false, code: 'bad_base64' } },
    { name: 'empty', input: '', expect: { ok: false, code: 'bad_base64' } },
    { name: 'not-a-string', input: 5, expect: { ok: false, code: 'bad_base64' } },
    { name: 'over-long', input: 'A'.repeat(2049), expect: { ok: false, code: 'too_long' } },
    { name: 'invalid-utf8', input: b64u(new Uint8Array([0xff, 0xfe])), expect: { ok: false, code: 'bad_utf8' } },
    { name: 'not-json', input: b64u(new TextEncoder().encode('{')), expect: { ok: false, code: 'bad_json' } },
    { name: 'duplicate-keys', input: b64u(new TextEncoder().encode('{"v":1,"v":1}')), expect: { ok: false, code: 'bad_json' } },
    { name: 'array', input: enc([]), expect: { ok: false, code: 'bad_shape' } },
    { name: 'wrong-version', input: enc({ ...need, v: 2 }), expect: { ok: false, code: 'bad_version' } },
    { name: 'unknown-kind', input: enc({ ...need, kind: 'admin' }), expect: { ok: false, code: 'bad_kind' } },
    { name: 'unknown-member', input: enc({ ...need, grant: 'x' }), expect: { ok: false, code: 'unknown_member' } },
    { name: 'empty-verb', input: enc({ ...need, verb: '' }), expect: { ok: false, code: 'bad_field' } },
    { name: 'scope-with-space', input: enc({ ...need, scopes: ['a b'] }), expect: { ok: false, code: 'bad_field' } },
    { name: 'negative-limit', input: enc({ ...need, limits: { 'money.usd': -1 } }), expect: { ok: false, code: 'bad_field' } },
    { name: 'null-limit', input: enc({ ...need, limits: { 'money.usd': null } }), expect: { ok: false, code: 'bad_field' } },
    { name: 'tier-on-scope-need', input: enc({ ...need, tier: 2 }), expect: { ok: false, code: 'bad_field' } },
    { name: 'escalate-without-tier', input: enc({ v: 1, kind: 'escalate', verb: 'v', resource: 'r' }), expect: { ok: false, code: 'bad_field' } },
    { name: 'tier-four', input: enc({ ...esc, tier: 4 }), expect: { ok: false, code: 'bad_field' } },
    { name: 'discharge-extra-member', input: enc({ ...need, kind: 'discharge', discharges: [{ issuer: 'https://i', claim: 'c', x: 1 }] }), expect: { ok: false, code: 'bad_field' } },
    { name: 'too-many-scopes', input: enc({ ...need, scopes: Array.from({ length: 17 }, (_, i) => `s${i}`) }), expect: { ok: false, code: 'bad_field' } },
  ];

  const tok = pcaPushToken('t1', IDS, SALT);
  const exp = { task_id: 't1', chain_ids: IDS, salt: SALT };
  const upd = (id: string) => ({ statusUpdate: { taskId: id, status: { state: 'TASK_STATE_COMPLETED' } } });
  const pushChecks = [
    { name: 'status-update', expected: exp, delivered: { token: tok, payload: upd('t1') }, expect: { ok: true } },
    { name: 'task-payload', expected: exp, delivered: { token: tok, payload: { task: { id: 't1' } } }, expect: { ok: true } },
    { name: 'artifact-update', expected: exp, delivered: { token: tok, payload: { artifactUpdate: { taskId: 't1' } } }, expect: { ok: true } },
    { name: 'no-token', expected: exp, delivered: { token: null, payload: upd('t1') }, expect: { ok: false, reason: 'no_token' } },
    { name: 'empty-token', expected: exp, delivered: { token: '', payload: upd('t1') }, expect: { ok: false, reason: 'no_token' } },
    { name: 'token-for-another-task', expected: exp, delivered: { token: pcaPushToken('t2', IDS, SALT), payload: upd('t1') }, expect: { ok: false, reason: 'token_mismatch' } },
    { name: 'token-for-another-chain', expected: exp, delivered: { token: pcaPushToken('t1', ['capA'], SALT), payload: upd('t1') }, expect: { ok: false, reason: 'token_mismatch' } },
    { name: 'token-with-another-salt', expected: exp, delivered: { token: pcaPushToken('t1', IDS, `${SALT}x`), payload: upd('t1') }, expect: { ok: false, reason: 'token_mismatch' } },
    { name: 'payload-about-another-task', expected: exp, delivered: { token: tok, payload: upd('t2') }, expect: { ok: false, reason: 'task_mismatch' } },
    { name: 'payload-not-an-object', expected: exp, delivered: { token: tok, payload: 'x' }, expect: { ok: false, reason: 'task_mismatch' } },
    { name: 'payload-without-a-task', expected: exp, delivered: { token: tok, payload: {} }, expect: { ok: false, reason: 'task_mismatch' } },
  ];
  const push = {
    tokens: [
      { task_id: 't1', chain_ids: IDS, salt: SALT, token: tok },
      { task_id: 't1', chain_ids: ['capA'], salt: SALT, token: pcaPushToken('t1', ['capA'], SALT) },
      { task_id: 't2', chain_ids: IDS, salt: SALT, token: pcaPushToken('t2', IDS, SALT) },
    ],
    weak_salts: ['', 'short', 'fifteen-chars!!'],
    checks: pushChecks,
  };

  const chains = [
    { name: 'two-hops-extending', chains: [['a'], ['a', 'b']], expect: { ok: true } },
    { name: 'same-chain-forwarded', chains: [['a', 'b'], ['a', 'b']], expect: { ok: true } },
    { name: 'three-hops', chains: [['a'], ['a', 'b'], ['a', 'b', 'c']], expect: { ok: true } },
    { name: 'single-hop', chains: [['a']], expect: { ok: true } },
    { name: 'unrelated-root', chains: [['a', 'b'], ['x', 'b', 'c']], expect: { ok: false, failedHop: 1, reason: 'chain_does_not_extend_previous_hop' } },
    { name: 'dropped-hop', chains: [['a', 'b'], ['a']], expect: { ok: false, failedHop: 1, reason: 'chain_does_not_extend_previous_hop' } },
    { name: 'reordered', chains: [['a', 'b'], ['b', 'a']], expect: { ok: false, failedHop: 1, reason: 'chain_does_not_extend_previous_hop' } },
    { name: 'third-hop-diverges', chains: [['a'], ['a', 'b'], ['a', 'x', 'c']], expect: { ok: false, failedHop: 2, reason: 'chain_does_not_extend_previous_hop' } },
    { name: 'empty-first-chain', chains: [[]], expect: { ok: false, failedHop: 0, reason: 'no_chain' } },
    { name: 'empty-later-chain', chains: [['a'], []], expect: { ok: false, failedHop: 1, reason: 'no_chain' } },
  ];

  const P = { verb: 'purchase', resource: 'cart/42' };
  const dg = pcaNeedDigest(need);
  const resume = [
    { name: 'ready', state: 'TASK_STATE_AUTH_REQUIRED', need_encoded: NEED, answer_need_digest: dg, proof_action: P, expect: null },
    { name: 'legacy-state-name', state: 'auth-required', need_encoded: NEED, answer_need_digest: dg, proof_action: P, expect: null },
    { name: 'input-required', state: 'TASK_STATE_INPUT_REQUIRED', need_encoded: NEED, answer_need_digest: dg, proof_action: P, expect: 'task_not_auth_required' },
    { name: 'working', state: 'TASK_STATE_WORKING', need_encoded: NEED, answer_need_digest: dg, proof_action: P, expect: 'task_not_auth_required' },
    { name: 'completed', state: 'TASK_STATE_COMPLETED', need_encoded: NEED, answer_need_digest: dg, proof_action: P, expect: 'task_not_auth_required' },
    { name: 'no-need', state: 'TASK_STATE_AUTH_REQUIRED', need_encoded: null, answer_need_digest: dg, proof_action: P, expect: 'no_valid_need' },
    { name: 'malformed-need', state: 'TASK_STATE_AUTH_REQUIRED', need_encoded: `${NEED}=`, answer_need_digest: dg, proof_action: P, expect: 'no_valid_need' },
    { name: 'unbound-answer', state: 'TASK_STATE_AUTH_REQUIRED', need_encoded: NEED, answer_need_digest: null, proof_action: P, expect: 'answer_not_bound_to_need' },
    { name: 'answer-for-another-need', state: 'TASK_STATE_AUTH_REQUIRED', need_encoded: NEED, answer_need_digest: pcaNeedDigest(esc), proof_action: P, expect: 'answer_not_bound_to_need' },
    { name: 'no-proof', state: 'TASK_STATE_AUTH_REQUIRED', need_encoded: NEED, answer_need_digest: dg, proof_action: null, expect: 'no_proof' },
    { name: 'proof-for-another-verb', state: 'TASK_STATE_AUTH_REQUIRED', need_encoded: NEED, answer_need_digest: dg, proof_action: { verb: 'refund', resource: 'cart/42' }, expect: 'action_mismatch' },
    { name: 'proof-for-another-resource', state: 'TASK_STATE_AUTH_REQUIRED', need_encoded: NEED, answer_need_digest: dg, proof_action: { verb: 'purchase', resource: 'cart/43' }, expect: 'action_mismatch' },
  ];

  const mk = (state: string, prev?: TaskReceipt, taskId = 't1', ids: string[] = IDS, secret = SECRET) => signTaskReceipt(secret, { taskId, state, chainIds: ids, issuedAt: NOW, ...(prev ? { prev } : {}) });
  const r0 = mk('TASK_STATE_WORKING');
  const r1 = mk('TASK_STATE_WORKING', r0);
  const r2 = mk('TASK_STATE_COMPLETED', r1);
  const failed = mk('TASK_STATE_FAILED', r0);
  const lone = mk('TASK_STATE_COMPLETED');
  const records: unknown[] = [
    r0, // 0
    r1, // 1
    r2, // 2: completed
    mk('TASK_STATE_COMPLETED', undefined, 't2'), // 3: another task
    mk('TASK_STATE_COMPLETED', undefined, 't1', ['capZ']), // 4: another chain
    mk('TASK_STATE_COMPLETED', undefined, 't1', IDS, OTHER), // 5: signed by an unpinned key
    { ...lone, state: 'TASK_STATE_FAILED' }, // 6: tampered after signing
    failed, // 7
    lone, // 8
    { ...r1, seq: 2, prev: receiptDigest(r2) }, // 9: claims to follow the terminal receipt (signature no longer matches)
    { ...lone, sig: 'x' }, // 10
  ];
  const sc = (name: string, indices: number[], expect: Record<string, unknown>, may: boolean) => ({ name, indices, task_id: 't1', chain_ids: IDS, expect, may_trigger_next: may });
  const receipts = {
    signer: SIGNER,
    task_id: 't1',
    chain_ids: IDS,
    records,
    digests: [{ record: 0, digest: receiptDigest(r0) }, { record: 2, digest: receiptDigest(r2) }],
    verify: records.map((_, i) => ({ record: i, ok: i === 0 || i === 1 || i === 2 || i === 3 || i === 4 || i === 7 || i === 8 })),
    scenarios: [
      sc('working-then-completed', [0, 1, 2], { ok: true, terminal: true, last_state: 'TASK_STATE_COMPLETED' }, true),
      sc('single-signed-completed', [8], { ok: true, terminal: true, last_state: 'TASK_STATE_COMPLETED' }, true),
      sc('failed-does-not-trigger', [0, 7], { ok: true, terminal: true, last_state: 'TASK_STATE_FAILED' }, false),
      sc('still-working', [0, 1], { ok: true, terminal: false, last_state: 'TASK_STATE_WORKING' }, false),
      sc('empty', [], { ok: false, code: 'empty' }, false),
      sc('another-task', [3], { ok: false, code: 'wrong_task', at: 0 }, false),
      sc('another-chain', [4], { ok: false, code: 'wrong_chain', at: 0 }, false),
      sc('unpinned-signer', [5], { ok: false, code: 'bad_receipt', at: 0 }, false),
      sc('tampered', [6], { ok: false, code: 'bad_receipt', at: 0 }, false),
      sc('bad-signature-string', [10], { ok: false, code: 'bad_receipt', at: 0 }, false),
      sc('gap-in-the-chain', [0, 2], { ok: false, code: 'broken_link', at: 1 }, false),
      sc('starts-mid-chain', [1], { ok: false, code: 'bad_start', at: 0 }, false),
      sc('repeated-receipt', [0, 0], { ok: false, code: 'broken_link', at: 1 }, false),
      sc('anything-after-terminal', [0, 7, 1], { ok: false, code: 'after_terminal', at: 2 }, false),
      sc('forged-follow-up-to-terminal', [0, 1, 2, 9], { ok: false, code: 'bad_receipt', at: 3 }, false),
    ],
  };

  // cross-check the hand-written expectations against the reference
  const bad: string[] = [];
  for (const c of needCases) {
    const r = decodePcaNeed(c.input);
    const flat = r.ok ? { ok: true, digest: pcaNeedDigest(r.need) } : { ok: false, code: r.code };
    if (JSON.stringify(flat) !== JSON.stringify(c.expect)) bad.push(`need/${c.name}: ${JSON.stringify(flat)}`);
  }
  for (const c of chains) if (JSON.stringify(checkChainExtension(c.chains)) !== JSON.stringify(c.expect)) bad.push(`chains/${c.name}`);
  for (const c of resume) {
    const want = c.expect;
    const got = resumeGate({ state: c.state, needEncoded: c.need_encoded ?? undefined, answerNeedDigest: c.answer_need_digest, proofAction: c.proof_action ?? undefined });
    if (got !== want) bad.push(`resume/${c.name}: ${got}`);
  }
  for (const c of pushChecks) {
    const got = checkPushNotification({ taskId: c.expected.task_id, chainIds: c.expected.chain_ids, salt: c.expected.salt }, { token: c.delivered.token ?? undefined, payload: c.delivered.payload });
    if (JSON.stringify(got) !== JSON.stringify(c.expect)) bad.push(`push/${c.name}: ${JSON.stringify(got)}`);
  }
  for (const s of receipts.scenarios) {
    const list = s.indices.map((i) => records[i]);
    const got = checkReceiptChain(list, { signer: SIGNER, taskId: 't1', chainIds: IDS });
    const flat = got.ok ? { ok: true, terminal: got.terminal, last_state: got.last.state } : { ok: false, code: got.code, ...(got.at !== undefined ? { at: got.at } : {}) };
    if (JSON.stringify(flat) !== JSON.stringify(s.expect)) bad.push(`receipts/${s.name}: ${JSON.stringify(flat)}`);
    if (mayTriggerNext(list, { signer: SIGNER, taskId: 't1', chainIds: IDS }) !== s.may_trigger_next) bad.push(`receipts/${s.name}/may`);
  }
  if (bad.length > 0) throw new Error(`a2a vectors drifted: ${bad.join('; ')}`);

  return {
    format: 1,
    about: 'Conformance vectors for the A2A binding: typed needs (pca_need), per-hop chain extension, the pure gate of AUTH_REQUIRED resumption, push-token binding and signed task-update receipts. Push token: base64url sha-256 of strict-canonical {"d":"atlas-pca/a2a-push/v1","task_id","chain":<chain digest>,"salt"}. Receipt: Ed25519 over "atlas-pca/a2a-receipt/v1" NUL then strict-canonical {v,task_id,state,seq,prev,chain,issued_at,signer}. Generated by scripts/gen-a2a-vectors.ts.',
    need: needCases,
    push,
    chains,
    resume,
    receipts,
  };
}
