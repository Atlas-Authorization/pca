import { b64u, publicKeyOf } from '@atlasauth/pca';
import { memoryLeaseKv } from '../lease';
import {
  LeaseRegistry, checkLease, signLease, signLeaseRevocation, signLeaseUnsafeOverCap, type Lease, type LeaseRevocation, type NewLease,
} from '../lease';

/**
 * Shared vectors for leases (packages/pca/conformance/lease-vectors.json): signed records and revocations under fixed test keys,
 * scenarios replayed against a fresh registry that pins the authority. Expectations are hand-written below and proved against
 * the reference before the file is written. Compared by the natives: ok / code / replaced / seq for accept, ok / revoked for
 * revoke, the whole decision for check (reason text is not compared). Generated by scripts/gen-lease-vectors.ts.
 */
const AUTH = new Uint8Array(32).fill(31);
const ROGUE = new Uint8Array(32).fill(32);
export const LEASE_AUTH = b64u(publicKeyOf(AUTH));
const T0 = 1_800_000_000_000;
const TTL = 3_600_000;
const base: NewLease = {
  lease_id: 'L1', path: 'db/prod/ro', grant_ref: 'g1', holder: 'agent', requester: 'alice', approvers: ['bob'], justification_digest: 'j1',
  seq: 1, issued_at: T0, renewed_at: T0, expires_at: T0 + 600_000, max_ttl: TTL,
};
const rec = (over: Partial<NewLease> = {}, secret = AUTH): Lease => signLease(secret, { ...base, ...over });
const renew = (seq: number, at: number, exp: number, j: string, over: Partial<NewLease> = {}) => rec({ seq, renewed_at: at, expires_at: exp, justification_digest: j, ...over });
const rev = (target: 'lease' | 'prefix' | 'grant', value: string, at: number): LeaseRevocation => signLeaseRevocation(AUTH, { target, value, revoked_at: at });
const L2 = { lease_id: 'L2', max_ttl: 900_000 };

export async function buildLeaseVectors() {
  const records: Lease[] = [
    rec(), // 0: L1 seq 1, expires T0+600k
    renew(2, T0 + 300_000, T0 + 900_000, 'j2'), // 1: renewal with a new reason
    renew(2, T0 + 300_000, T0 + 900_000, 'j1'), // 2: renewal replaying the old reason
    renew(3, T0 + 600_000 - 1, T0 + 1_200_000, 'j3'), // 3: seq 3 (needs 1 first)
    renew(2, T0 + 300_000, T0 + 950_000, 'j9'), // 4: a different seq 2 (fork of 1)
    renew(2, T0 + 300_000, T0 + 900_000, 'j2', { holder: 'other' }), // 5: renewal that changes the holder
    renew(2, T0 + 700_000, T0 + 1_300_000, 'j2'), // 6: renewal after expiry
    renew(2, T0 + 300_000, T0 + 600_000, 'j2'), // 7: renewal that does not extend
    rec({}, ROGUE), // 8: unknown authority
    { ...rec(), expires_at: T0 + 900_000 } as Lease, // 9: tampered after signing
    rec({ approvers: ['alice'] }), // 10: requester approves own request
    rec({ approvers: ['agent'] }), // 11: holder approves own lease
    rec({ approvers: ['bob', 'bob'] }), // 12: duplicate approver
    rec({ approvers: ['bob', 'carol'] }), // 13: two approvers
    rec({ ...L2 }), // 14: L2 seq 1, max_ttl 900k, expires T0+600k
    renew(2, T0 + 500_000, T0 + 900_000, 'j2', L2), // 15: L2 renewed to exactly the cap
    signLeaseUnsafeOverCap(AUTH, { ...base, ...L2, seq: 3, renewed_at: T0 + 800_000, expires_at: T0 + 900_001, justification_digest: 'j3' }), // 16: past the cap
    rec({ lease_id: 'L9', issued_at: T0 + 200_000, renewed_at: T0 + 200_000, expires_at: T0 + 800_000 }), // 17: a new lease under a revoked prefix, issued after the revocation
    rec({ lease_id: 'L3', path: 'db/production', grant_ref: 'g3' }), // 18: sibling path (not under db/prod)
    rec({ approvers: ['bob', 'dave'] }), // 19: dave is not eligible when eligible = [bob, carol]
    rec({ approvers: [] }), // 20: no approver at all
    renew(2, T0 + 599_999, T0 + 1_199_999, 'j2'), // 21: renewed the last millisecond before expiry
    renew(2, T0 + 600_000, T0 + 1_200_000, 'j2'), // 22: renewed at the expiry instant
  ];
  const revocations = [
    rev('lease', 'L1', T0 + 100_000), // 0
    rev('prefix', 'db/prod', T0 + 100_000), // 1
    rev('prefix', 'db/pro', T0 + 100_000), // 2: not a segment boundary, covers nothing
    rev('grant', 'g1', T0 + 100_000), // 3
    { ...rev('lease', 'L1', T0 + 100_000), value: 'L2' } as LeaseRevocation, // 4: tampered
  ];
  const ok = (replaced: boolean, seq: number) => ({ ok: true, replaced, seq });
  const no = (code: string) => ({ ok: false, code });
  const accept = (record: number, expect: object, chain?: string[]) => ({ op: 'accept', record, ...(chain ? { chain } : {}), expect });
  const revoke = (revocation: number, expect: object) => ({ op: 'revoke', revocation, expect });
  const check = (record: number, now: number, expect: object) => ({ op: 'check', record, now, expect });
  const live = (id: string, exp: number) => ({ decision: 'allow', lease_id: id, expires_at: exp });
  const dead = (code: string, id = 'L1') => ({ decision: 'deny', code, lease_id: id });
  const revoked = (n: number) => ({ ok: true, revoked: n });
  const scenarios: { name: string; policy?: Record<string, unknown>; steps: Record<string, unknown>[] }[] = [
    { name: 'issue-then-check-then-expire', steps: [accept(0, ok(true, 1)), check(0, T0, live('L1', T0 + 600_000)), check(0, T0 + 599_999, live('L1', T0 + 600_000)), check(0, T0 + 600_000, dead('expired')), check(0, T0 - 1, dead('not_yet_valid'))] },
    { name: 'renewal-window-is-open-until-the-expiry-instant', steps: [accept(0, ok(true, 1)), accept(21, ok(true, 2)), check(21, T0 + 599_999, live('L1', T0 + 1_199_999))] },
    { name: 'renewal-at-the-expiry-instant-is-too-late', steps: [accept(0, ok(true, 1)), accept(22, no('expired_lease'))] },
    { name: 'renewal-supersedes-the-old-record', steps: [accept(0, ok(true, 1)), accept(1, ok(true, 2)), check(1, T0 + 700_000, live('L1', T0 + 900_000)), check(0, T0 + 400_000, dead('superseded'))] },
    { name: 'renewal-replaying-the-reason-is-refused', steps: [accept(0, ok(true, 1)), accept(2, no('stale_justification'))] },
    { name: 'renewal-replaying-the-reason-allowed-when-not-required', policy: { freshJustification: false }, steps: [accept(0, ok(true, 1)), accept(2, ok(true, 2))] },
    { name: 'seq-gap-refused', steps: [accept(0, ok(true, 1)), accept(3, no('bad_seq')), accept(1, ok(true, 2)), accept(3, ok(true, 3))] },
    { name: 'a-new-lease-must-start-at-seq-1', steps: [accept(1, no('bad_seq'))] },
    { name: 'same-seq-different-record-is-a-fork', steps: [accept(0, ok(true, 1)), accept(1, ok(true, 2)), accept(4, no('lease_fork')), accept(1, ok(false, 2))] },
    { name: 'older-seq-is-stale', steps: [accept(0, ok(true, 1)), accept(1, ok(true, 2)), accept(0, no('stale_seq'))] },
    { name: 'renewal-may-not-change-identity', steps: [accept(0, ok(true, 1)), accept(5, no('renewal_mismatch'))] },
    { name: 'expired-lease-cannot-be-renewed', steps: [accept(0, ok(true, 1)), accept(6, no('expired_lease'))] },
    { name: 'renewal-must-extend', steps: [accept(0, ok(true, 1)), accept(7, no('not_extending'))] },
    { name: 'max-ttl-is-a-hard-cap', steps: [accept(14, ok(true, 1)), accept(15, ok(true, 2)), check(15, T0 + 899_999, live('L2', T0 + 900_000)), check(15, T0 + 900_000, dead('past_max_ttl', 'L2')), accept(16, no('over_max_ttl'))] },
    { name: 'unknown-authority-refused', steps: [accept(8, no('unknown_authority')), check(8, T0 + 1, dead('unknown_lease'))] },
    { name: 'tampered-record-refused', steps: [accept(9, no('bad_record')), check(9, T0 + 1, { decision: 'deny', code: 'bad_record' })] },
    { name: 'sod-requester-may-not-approve', steps: [accept(10, no('sod'))] },
    { name: 'sod-holder-may-not-approve', steps: [accept(11, no('sod'))] },
    { name: 'sod-duplicate-approver', steps: [accept(12, no('sod'))] },
    { name: 'sod-approver-in-the-holders-chain', steps: [accept(0, no('sod'), ['root', 'bob', 'agent']), accept(0, ok(true, 1), ['root', 'agent'])] },
    { name: 'sod-k-of-n-needs-k-distinct-approvers', policy: { minApprovals: 2 }, steps: [accept(0, no('sod')), accept(13, ok(true, 1))] },
    { name: 'sod-eligible-approvers-only', policy: { eligibleApprovers: ['bob', 'carol'] }, steps: [accept(19, no('sod')), accept(13, ok(true, 1))] },
    { name: 'sod-zero-approvals-refused-by-default', steps: [accept(20, no('sod'))] },
    { name: 'revoke-by-id-blocks-renewal-and-check', steps: [accept(0, ok(true, 1)), revoke(0, revoked(1)), check(0, T0 + 200_000, dead('revoked')), accept(1, no('revoked'))] },
    { name: 'revoke-by-prefix-kills-everything-under-it', steps: [accept(0, ok(true, 1)), accept(14, ok(true, 1)), accept(18, ok(true, 1)), revoke(1, revoked(2)), check(0, T0 + 200_000, dead('revoked')), check(14, T0 + 200_000, dead('revoked', 'L2')), check(18, T0 + 200_000, live('L3', T0 + 600_000))] },
    { name: 'revoke-prefix-is-segment-bounded', steps: [accept(0, ok(true, 1)), revoke(2, revoked(0)), check(0, T0 + 200_000, live('L1', T0 + 600_000))] },
    { name: 'a-lease-issued-after-a-prefix-revocation-is-new', steps: [revoke(1, revoked(0)), accept(17, ok(true, 1)), check(17, T0 + 300_000, live('L9', T0 + 800_000))] },
    { name: 'revoking-the-grant-revokes-its-leases', steps: [accept(0, ok(true, 1)), accept(18, ok(true, 1)), revoke(3, revoked(1)), check(0, T0 + 200_000, dead('revoked')), check(18, T0 + 200_000, live('L3', T0 + 600_000))] },
    { name: 'tampered-revocation-refused', steps: [revoke(4, { ok: false, code: 'bad_record' })] },
    { name: 'unknown-lease', steps: [check(0, T0 + 1, { decision: 'deny', code: 'unknown_lease', lease_id: 'L1' })] },
    { name: 'bad-clock', steps: [accept(0, ok(true, 1)), check(0, 1.5, { decision: 'deny', code: 'bad_input' })] },
  ];
  for (const s of scenarios) {
    const reg = new LeaseRegistry({ authorities: [LEASE_AUTH], ...(s.policy ?? {}) } as never, memoryLeaseKv());
    for (const st of s.steps) {
      let got: unknown;
      if (st.op === 'accept') {
        const r = await reg.accept(records[st.record as number], (st.chain as string[] | undefined) ?? []);
        got = r.ok ? { ok: true, replaced: r.replaced, seq: r.seq } : { ok: false, code: r.code };
      } else if (st.op === 'revoke') {
        const r = await reg.revoke(revocations[st.revocation as number]);
        got = r.ok ? { ok: true, revoked: r.revoked } : { ok: false, code: r.code };
      } else {
        got = await checkLease(records[st.record as number], reg, st.now as number);
      }
      if (JSON.stringify(got) !== JSON.stringify(st.expect)) throw new Error(`${s.name}: ${st.op} ${JSON.stringify(got)} != ${JSON.stringify(st.expect)}`);
    }
  }
  return {
    format: 1,
    about: 'Conformance vectors for leases. Records and revocations are signed under fixed test keys; each scenario runs against a fresh registry that pins the authority (plus the scenario policy: minApprovals, eligibleApprovers, freshJustification default true). accept compares ok/code/replaced/seq, revoke ok/code/revoked, check the whole decision. Lease body signed: domain atlas-pca/lease/v1 NUL then strict-canonical JSON of {v,lease_id,path,grant_ref,holder,requester,approvers,justification_digest,seq,issued_at,renewed_at,expires_at,max_ttl,authority}; revocation: atlas-pca/lease-revoke/v1 NUL over {v,target,value,revoked_at,authority}. Rules: renewal = seq+1, same identity fields, later expires_at, renewed_at before the old expiry, expires_at <= issued_at+max_ttl, new justification unless freshJustification=false; SoD: approvers distinct, not requester, not holder, not in the supplied chain, in eligibleApprovers when set, count >= minApprovals; a prefix covers a path at a segment boundary; a revocation covers leases with issued_at <= revoked_at. Generated by scripts/gen-lease-vectors.ts.',
    authority: LEASE_AUTH,
    records,
    revocations,
    scenarios,
  };
}
