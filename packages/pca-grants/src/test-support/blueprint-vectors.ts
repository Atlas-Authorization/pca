import { b64u, publicKeyOf } from '@atlasauth/pca';
import { MemoryBlueprintStore } from '../blueprint';
import { BlueprintRegistry, checkBlueprints, signBlueprint, type AgentBlueprint, type NewBlueprint } from '../blueprint';

/**
 * Shared vectors for agent blueprints (packages/pca/conformance/blueprint-vectors.json): signed records under fixed test keys and
 * scenarios replayed against a fresh registry. Expected results are written by hand below, the signatures are produced here.
 * Only the cases a native verifier can decide are included: the ceiling is empty, or absent evaluator input makes it
 * `ceiling_unevaluable` (fail closed), so no native needs a caveat evaluator to pass. Generated by scripts/gen-blueprint-vectors.ts.
 */
const OPERATOR = new Uint8Array(32).fill(11);
const ROGUE = new Uint8Array(32).fill(12);
const pk = (s: Uint8Array) => b64u(publicKeyOf(s));
export const OP = pk(OPERATOR);
const KEY = pk(new Uint8Array(32).fill(21));
const NOW = 1_800_000_000_000;
const base: NewBlueprint = { id: 'support-bot', key: KEY, ceiling: [], max_depth: 2, epoch: 1, status: 'active', issued_at: NOW };
const rec = (over: Partial<NewBlueprint> = {}, secret = OPERATOR): AgentBlueprint => signBlueprint(secret, { ...base, ...over });
const hop = (issuer: string, holder: string) => ({ issuer, holder });
const I1 = [hop('principal', KEY), hop(KEY, 'inst1')];
const I2 = [hop('principal', KEY), hop(KEY, 'inst2')];
const DEEP = [hop('principal', KEY), hop(KEY, 'inst1'), hop('inst1', 'sub')];
const o = (extra: Record<string, unknown> = {}) => ({ now: NOW, mode: 'require', ...extra });
type Step =
  | { op: 'accept'; record: number; expect: Record<string, unknown> }
  | { op: 'check'; chain: unknown[]; opts: Record<string, unknown>; expect: Record<string, unknown> };
const accept = (record: number, expect: Record<string, unknown>): Step => ({ op: 'accept', record, expect });
const check = (chain: unknown[], opts: Record<string, unknown>, expect: Record<string, unknown>): Step => ({ op: 'check', chain, opts, expect });
const ok = { ok: true, replaced: true };
const allow = (governed: string[]) => ({ decision: 'allow', governed });
const deny = (code: string, extra: Record<string, unknown> = {}) => ({ decision: 'deny', code, ...extra });

export async function buildBlueprintVectors() {
  const records = [
    rec(), // 0: epoch 1 active
    rec({ epoch: 2, status: 'disabled' }), // 1: the group kill
    rec({ epoch: 3 }), // 2: re-enabled
    rec({ epoch: 2 }), // 3: a different epoch-2 record (active) = fork of 1
    rec({ epoch: 9 }, ROGUE), // 4: unknown operator
    rec({ expires_at: NOW }), // 5: expired at now
    rec({ max_depth: 1 }), // 6
    rec({ ceiling: [{ type: 'reversibility_max', class: 'reversible' }] }), // 7: a ceiling nobody evaluates here
    { ...rec(), status: 'disabled' } as AgentBlueprint, // 8: tampered after signing
  ];
  const scenarios = [
    { name: 'active-instance-allowed', steps: [accept(0, ok), check(I1, o(), allow(['support-bot']))] },
    { name: 'group-kill-refuses-seen-and-never-seen-instances', steps: [accept(0, ok), check(I1, o(), allow(['support-bot'])), accept(1, ok), check(I1, o(), deny('blueprint_disabled', { blueprint: 'support-bot' })), check(I2, o(), deny('blueprint_disabled', { blueprint: 'support-bot' }))] },
    { name: 'older-record-cannot-revive', steps: [accept(0, ok), accept(1, ok), accept(0, { ok: false, code: 'stale_epoch' }), check(I1, o(), deny('blueprint_disabled', { blueprint: 'support-bot' }))] },
    { name: 'same-epoch-different-record-is-a-fork', steps: [accept(0, ok), accept(1, ok), accept(3, { ok: false, code: 'epoch_fork' }), check(I1, o(), deny('blueprint_disabled', { blueprint: 'support-bot' }))] },
    { name: 'higher-epoch-re-enables', steps: [accept(0, ok), accept(1, ok), accept(2, ok), check(I1, o(), allow(['support-bot']))] },
    { name: 'identical-record-again-is-a-no-op', steps: [accept(0, ok), accept(0, { ok: true, replaced: false })] },
    { name: 'unknown-operator-refused', steps: [accept(4, { ok: false, code: 'unknown_operator' }), check(I1, o(), deny('no_blueprint'))] },
    { name: 'tampered-record-refused', steps: [accept(8, { ok: false, code: 'bad_record' })] },
    { name: 'expired-at-now', steps: [accept(5, ok), check(I1, o(), deny('blueprint_expired', { blueprint: 'support-bot' }))] },
    { name: 'depth-limit', steps: [accept(0, ok), check(DEEP, o(), allow(['support-bot'])), accept(6, { ok: false, code: 'epoch_fork' })] },
    { name: 'depth-limit-one', steps: [accept(6, ok), check(I1, o(), allow(['support-bot'])), check(DEEP, o(), deny('too_deep', { blueprint: 'support-bot' }))] },
    { name: 'ceiling-not-evaluable-without-an-evaluator-denies', steps: [accept(7, ok), check(I1, o(), deny('ceiling_unevaluable', { blueprint: 'support-bot' }))] },
    { name: 'require-mode-refuses-a-chain-without-a-blueprint-hop', steps: [accept(0, ok), check([hop('principal', 'agent')], o(), deny('no_blueprint')), check([hop('principal', 'agent')], o({ mode: 'any' }), allow([]))] },
    { name: 'broken-link', steps: [accept(0, ok), check([hop(KEY, 'inst1')], o(), deny('broken_link', { blueprint: 'support-bot' })), check([hop('principal', 'x'), hop(KEY, 'inst1')], o(), deny('broken_link', { blueprint: 'support-bot' }))] },
    { name: 'stale-registry-escalates', steps: [accept(0, ok), check(I1, o({ minEpoch: 1 }), allow(['support-bot'])), check(I1, o({ minEpoch: 2 }), { decision: 'escalate', code: 'stale_blueprint_state', have: 1, need: 2 })] },
    { name: 'bad-input', steps: [check([], o(), deny('bad_input')), check(I1, o({ now: 1.5 }), deny('bad_input'))] },
  ];
  // the expectations above are hand-written; prove here that the reference agrees, so a drifted builder cannot ship
  for (const s of scenarios) {
    const reg = new BlueprintRegistry([OP], new MemoryBlueprintStore());
    for (const st of s.steps) {
      if (st.op === 'accept') {
        const got = await reg.accept(records[st.record]);
        if (JSON.stringify(got) !== JSON.stringify(st.expect)) throw new Error(`${s.name}: accept ${JSON.stringify(got)} != ${JSON.stringify(st.expect)}`);
      } else {
        const got = await checkBlueprints(st.chain as never, reg, st.opts as never);
        if (JSON.stringify(got) !== JSON.stringify(st.expect)) throw new Error(`${s.name}: check ${JSON.stringify(got)} != ${JSON.stringify(st.expect)}`);
      }
    }
  }
  return {
    format: 1,
    about: 'Conformance vectors for agent blueprints. Records are signed under fixed test keys; scenarios run against a fresh registry that pins the operator. Body signed: domain atlas-pca/agent-blueprint/v1 NUL then strict-canonical JSON of {v,id,key,ceiling,max_depth?,expires_at?,epoch,status,issued_at,operator}. Generated by scripts/gen-blueprint-vectors.ts.',
    operator: OP,
    records,
    scenarios,
  };
}
