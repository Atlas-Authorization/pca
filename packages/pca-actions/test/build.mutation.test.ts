// Exact behaviour of the build step that the other tests leave open: the generated TypeScript text, the pack body, the pack size
// limit, every refusal of the pack consistency check and of pack verification, and the signed message.
import { canonicalBytesStrict, generateKeyPair, utf8, verifyPinnedSuite } from '@atlasauth/pca';
import { describe, expect, it } from 'vitest';
import {
  CORE_REGISTRY, MAX_PACK_DEFS, PACK_SIGN_DOMAIN, buildArtifacts, generateTypes, loadActionsText, packConsistencyError, packKeyOf, signPack, validateDef, verifyPack,
  type ActionDef, type BuildConfig,
} from '../src';

const HELLO = `
ns: acme
since: 0.1.0
actions:
  - verb: acme.invoice.send
    title: Send an invoice
    description: Emails an existing invoice to the customer.
    effects: [send]
    resource: acme.invoice:inv_*
    params: {invoice: "id:acme.invoice", to: email, note: "message(500)"}
  - verb: acme.charge.refund
    title: Refund a charge
    description: Returns money.
    effects: [pay]
    resource: acme.charge:ch_*
    params: {charge: "id:acme.charge", amount: "money(USD, max=100000)"}
    bindings: {mcp: {tool: refund_charge}}
`;
const defs = (): ActionDef[] => loadActionsText(HELLO).defs;
const cfg: BuildConfig = { ns: 'acme', version: '0.1.0', stability: 'draft', site: 'https://acme.example.com', aud: 'acme-api' };
const raw = (verb: string, params: Record<string, object>): ActionDef => ({ verb, params }) as unknown as ActionDef;

describe('generateTypes', () => {
  it('is exactly this text: defs and keys sorted, unusual names quoted, nested names nested', () => {
    const t = generateTypes([
      raw('z.y', { n: { type: 'integer' } }),
      raw('a.b', { 'a-x': { type: 'boolean' }, 'a.b': { type: 'duration', required: false } }),
    ]);
    expect(t).toBe([
      '// Generated by `pca actions build`. Do not edit.',
      '',
      'export interface ABParams {',
      '  a: {',
      '    b?: number;',
      '  };',
      '  "a-x": boolean;',
      '}',
      '',
      'export interface ZYParams {',
      '  n: number;',
      '}',
      '',
      'export interface ActionParams {',
      '  "a.b": ABParams;',
      '  "z.y": ZYParams;',
      '}',
      '',
      'export type ActionVerb = keyof ActionParams;',
      '',
    ].join('\n'));
  });
  it('no defs is just the header and the empty maps', () => {
    expect(generateTypes([])).toBe(['// Generated by `pca actions build`. Do not edit.', '', 'export interface ActionParams {', '}', '', 'export type ActionVerb = keyof ActionParams;', ''].join('\n'));
  });
  it('a def with equal verbs keeps its input order', () => {
    const t = generateTypes([raw('a.b', { x: { type: 'boolean' } }), raw('a.b', { y: { type: 'boolean' } })]);
    expect(t.indexOf('x: boolean')).toBeGreaterThan(-1);
    expect(t.indexOf('x: boolean')).toBeLessThan(t.indexOf('y: boolean'));
  });
  it('names that do not start like an identifier or hold other characters are quoted', () => {
    const t = generateTypes([raw('a.b', { '1a': { type: 'boolean' }, 'a-b': { type: 'boolean' }, _ok9: { type: 'boolean' }, Ok: { type: 'boolean' } })]);
    expect(t).toContain('  "1a": boolean;');
    expect(t).toContain('  "a-b": boolean;');
    expect(t).toContain('  _ok9: boolean;');
    expect(t).toContain('  Ok: boolean;');
  });
  it('each param type has its TypeScript type', () => {
    const t = generateTypes([raw('a.b', {
      i: { type: 'integer' }, d: { type: 'duration' }, b: { type: 'boolean' },
      set1: { type: 'set', values: ['x', 'y'] }, set2: { type: 'set' }, set3: { type: 'set', values: [] },
      arr1: { type: 'array', items: 'integer' }, arr2: { type: 'array', items: 'string' }, arr3: { type: 'array' },
      en: { type: 'string', values: ['s', 'm'] }, str: { type: 'string' }, dt: { type: 'datetime' },
    })]);
    for (const l of [
      '  arr1: number[];', '  arr2: string[];', '  arr3: string[];', '  b: boolean;', '  d: number;', '  dt: string;', '  en: "s" | "m";', '  i: number;',
      '  set1: Array<"x" | "y">;', '  set2: Array<string>;', '  set3: Array<string>;', '  str: string;',
    ]) expect(t).toContain(`${l}\n`);
  });
});

describe('buildArtifacts', () => {
  it('the pack body is exactly the config, an empty evolution and no previous pack', () => {
    const { pack } = buildArtifacts(defs(), cfg, CORE_REGISTRY);
    expect(pack).toMatchObject({ v: 1, kind: 'pca-action-pack', ns: 'acme', version: '0.1.0', stability: 'draft', prev: null, evolution: [] });
    expect(Object.keys(pack).sort()).toEqual(['defs', 'evolution', 'kind', 'ns', 'prev', 'roles_digest', 'root', 'rules_digest', 'stability', 'traits_digest', 'v', 'version']);
  });
  it('the generated types list the defs in verb order whatever the input order', () => {
    const o = buildArtifacts([...defs()].reverse(), cfg, CORE_REGISTRY);
    expect(o.types.indexOf('AcmeChargeRefundParams')).toBeLessThan(o.types.indexOf('AcmeInvoiceSendParams'));
    expect(o.types).toBe(generateTypes(defs()));
  });
  it('a pack of exactly the limit is built and is consistent; one more def is refused', () => {
    const one = defs()[0]!;
    const mk = (n: number) => Array.from({ length: n }, (_, i) => ({ ...one, verb: `acme.n${i}.send` }));
    const big = buildArtifacts(mk(MAX_PACK_DEFS), cfg, CORE_REGISTRY);
    expect(big.pack.defs).toHaveLength(MAX_PACK_DEFS);
    expect(packConsistencyError(big.pack, CORE_REGISTRY)).toBeNull();
    expect(() => buildArtifacts(mk(MAX_PACK_DEFS + 1), cfg, CORE_REGISTRY)).toThrow(`a pack above ${MAX_PACK_DEFS} defs must be sharded (${MAX_PACK_DEFS + 1} given)`);
  });
});

describe('packConsistencyError', () => {
  const pack = () => buildArtifacts(defs(), cfg, CORE_REGISTRY).pack;
  const err = (p: unknown) => packConsistencyError(p, CORE_REGISTRY);
  it('the control is consistent', () => expect(err(pack())).toBeNull());
  it.each([[null], ['text'], [5], [[]]])('%j is not an object', (p) => {
    expect(err(p)).toBe('the pack must be an object');
  });
  it('a wrong kind or version is refused', () => {
    expect(err({ ...pack(), kind: 'x' })).toBe('not a pca-action-pack v1');
    expect(err({ ...pack(), v: 2 })).toBe('not a pca-action-pack v1');
  });
  it('defs must be a list within the limit', () => {
    const msg = 'defs must be a list within the unsharded limit';
    expect(err({ ...pack(), defs: 'oops' })).toBe(msg);
    expect(err({ ...pack(), defs: { length: 1 } })).toBe(msg);
    expect(err({ ...pack(), defs: Array.from({ length: MAX_PACK_DEFS + 1 }, () => pack().defs[0]) })).toBe(msg);
  });
  it('an invalid def is named by its verb, or by ? when it has none', () => {
    const bad = { ...pack().defs[0]!, bogus: 1 } as never;
    expect(validateDef(bad)).not.toBeNull();
    expect(err({ ...pack(), defs: [bad] })).toBe(`def ${(bad as { verb: string }).verb}: ${validateDef(bad)}`);
    expect(validateDef({} as never)).not.toBeNull();
    expect(err({ ...pack(), defs: [{}] })).toBe(`def ?: ${validateDef({} as never)}`);
    expect(validateDef(null as never)).not.toBeNull();
    expect(err({ ...pack(), defs: [null] })).toBe(`def ?: ${validateDef(null as never)}`);
  });
  it('a duplicate verb, a wrong root and a wrong traits digest are refused', () => {
    const p = pack();
    expect(err({ ...p, defs: [p.defs[0], p.defs[0]] })).toBe(`verb '${p.defs[0]!.verb}' is defined twice`);
    expect(err({ ...p, root: 'AAAA' })).toBe('the pack root does not match its defs');
    expect(err({ ...p, traits_digest: 'AAAA' })).toBe('traits_digest does not match the trait registry');
  });
  it('an error while reading the pack is reported, never thrown', () => {
    const evil = { ...pack() };
    Object.defineProperty(evil, 'defs', { enumerable: true, get() { throw new Error('boom'); } });
    expect(err(evil)).toBe('malformed pack: boom');
  });
});

describe('verifyPack: every refusal, with its exact reason', () => {
  const kp = generateKeyPair();
  const key = packKeyOf('reg-1', kp.secretKey);
  const s = signPack(buildArtifacts(defs(), cfg, CORE_REGISTRY).pack, 'reg-1', kp.secretKey, CORE_REGISTRY);
  const v = (p: unknown, keys = [key]) => verifyPack(p, keys, CORE_REGISTRY);
  it('the control verifies', () => expect(v(s)).toEqual({ ok: true }));
  it.each([
    ['an algorithm other than ed25519', { alg: 'rsa' }],
    ['a key id that is not a string', { kid: 5 }],
    ['a value that is not a string', { value: 5 }],
  ])('a signature with %s is malformed', (_l, over) => {
    expect(v({ ...s, sig: { ...s.sig, ...over } })).toEqual({ ok: false, reason: 'missing or malformed signature' });
  });
  it('a key entry with another algorithm or an undecodable key is malformed', () => {
    const MAL = { ok: false, reason: 'the registry key entry is malformed' };
    expect(v(s, [{ ...key, alg: 'rsa' as never }])).toEqual(MAL);
    expect(v(s, [{ ...key, pk: 'AAAA' }])).toEqual(MAL);
    expect(v(s, [{ ...key, alg: 'rsa' as never, pk: 'AAAA' }])).toEqual(MAL);
  });
  it('an unknown key id names the id', () => {
    expect(v(s, [{ ...key, kid: 'other' }])).toEqual({ ok: false, reason: "no registry key with kid 'reg-1'" });
  });
  it('an error while reading the signature is reported, never thrown', () => {
    const evil = { ...s };
    Object.defineProperty(evil, 'sig', { enumerable: true, get() { throw new Error('boom'); } });
    expect(v(evil)).toEqual({ ok: false, reason: 'pack verification error: boom' });
  });
});

describe('signPack: the signed message is the domain followed by the canonical body', () => {
  it('an independent verifier accepts the signature', () => {
    const kp = generateKeyPair();
    const { sig, ...body } = signPack(buildArtifacts(defs(), cfg, CORE_REGISTRY).pack, 'k', kp.secretKey, CORE_REGISTRY);
    const dom = utf8(PACK_SIGN_DOMAIN);
    const bytes = canonicalBytesStrict(body);
    const msg = new Uint8Array(dom.length + bytes.length);
    msg.set(dom);
    msg.set(bytes, dom.length);
    expect(verifyPinnedSuite('ed25519', packKeyOf('k', kp.secretKey).pk, undefined, msg, { sig: sig.value }, {})).toBe(true);
    expect(verifyPinnedSuite('ed25519', packKeyOf('k', kp.secretKey).pk, undefined, bytes, { sig: sig.value }, {})).toBe(false);
  });
});
