// gen-catalog.ts [--check] - write (or verify byte-identical) packages/pca/src/catalog-builtin.generated.ts, the facade's built-in
// connector catalog, DERIVED from the 21 reviewed built-in ActionDefs (the facade package cannot import this one). Run from the
// repo root: pnpm --filter @atlasauth/pca-actions exec tsx scripts/gen-catalog.ts [--check]
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { BUILTIN_DEFS, CORE_REGISTRY, facadeSpecs } from '../src';

export function render(): string {
  const rows = facadeSpecs(BUILTIN_DEFS, CORE_REGISTRY, { reviewed: true }).map((s) => {
    const f: string[] = [
      `connector: ${JSON.stringify(s.connector)}`, `action: ${JSON.stringify(s.action)}`, `verb: ${JSON.stringify(s.verb)}`,
      `reversibility: ${JSON.stringify(s.reversibility)}`, `blastRadius: ${s.blastRadius}`,
    ];
    if (s.amountField !== undefined) f.push(`amountField: ${JSON.stringify(s.amountField)}`);
    f.push(`description: ${JSON.stringify(s.description)}`);
    if (s.aliases) f.push(`aliases: ${JSON.stringify(s.aliases)}`);
    if (s.traits) f.push(`traits: ${JSON.stringify(s.traits)}`);
    return `  { ${f.join(', ')} },`;
  });
  return [
    '// GENERATED by packages/pca-actions/scripts/gen-catalog.ts from the built-in ActionDefs. Do not edit: change the def and regenerate',
    '// (CI runs the generator with --check). Reversibility and blast are the EFFECTIVE values (declared joined with the trait floors).',
    "import type { ActionSpec } from './catalog';",
    '',
    'export const BUILTIN_ACTIONS: ActionSpec[] = [',
    ...rows,
    '];',
    '',
  ].join('\n');
}

if (require.main === module) {
  const file = resolve(__dirname, '../../pca/src/catalog-builtin.generated.ts');
  const body = render();
  if (process.argv.includes('--check')) {
    if (!existsSync(file) || readFileSync(file, 'utf8') !== body) { console.error('catalog-builtin.generated.ts is stale: run scripts/gen-catalog.ts'); process.exit(1); }
    console.log('OK: catalog-builtin.generated.ts matches the built-in defs');
  } else { writeFileSync(file, body); console.log(`wrote ${file}`); }
}
